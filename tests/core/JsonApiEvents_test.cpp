/*******************************************************************************
 * E4.0d - REAL TIME EVENTS: the second surface of the JSON API, and the one
 * nobody was testing. Before this file, the whole event path had ZERO tests:
 * not CalaosEvent::toJson(), not one of the 23 strings of typeToString(), not
 * the "msg":"event" envelope, not the !loggedin gating, not poll_listen.
 *
 * Read tests/core/JsonApiCharacterization.h first. Semantic oracle, goldens
 * GENERATED by CALAOS_GOLDEN_UPDATE=1, never hand written, and never a
 * comparison of serialized JSON text.
 *
 * ---------------------------------------------------------------------------
 * THE WIRE CONTRACT THIS FILE FREEZES
 * ---------------------------------------------------------------------------
 * WS (JsonApiHandlerWS::handleEvents(), :53-60 + sendJson(), :62-73):
 *
 *   {"msg":"event",
 *    "data":{"event_raw":"io_changed id:e40_bool_out state:true",
 *            "type":"3",
 *            "type_str":"io_changed",
 *            "data":{"id":"e40_bool_out","state":"true"}}}
 *
 * Four things that a different JSON library could change without a sound, so
 * each has its own case below:
 *   1. data.data IS NESTED. The event object is the "data" of the envelope,
 *      and the event parameters are the "data" of the event object.
 *   2. EVERYTHING IS A STRING. Including "type", which is the enum integer run
 *      through Utils::to_string() and emitted as a JSON string ("3", not 3).
 *      Including a parameter that looks like a number ("21.5", "42").
 *   3. THE ENUM NUMBERING IS PART OF THE WIRE FORMAT. "type":"3" only means
 *      io_changed because EventIOChanged happens to be the fourth constant of
 *      an unnumbered enum. Inserting a constant in EventManager.h renumbers
 *      every event above it for every client. EnumNumberingIsPartOfTheWire
 *      pins the 24 integers.
 *   4. THERE IS NO msg_id. An event is an unsolicited push; sendJson() only
 *      writes msg_id when client_id is non empty (JsonApiHandlerWS.cpp:66).
 *
 * event_raw is a FLAT url-encoded string, not JSON: "<type_str>[ k:v]*", with
 * key and value both passed through Utils::url_encode() (StringUtils.cpp:34),
 * which keeps only [A-Za-z0-9_] and percent-encodes everything else - a dot, a
 * space and a UTF-8 byte all get escaped. The SAME values appear raw and
 * unescaped in data.data, so every event carries its parameters twice in two
 * different encodings. Params is a std::map, so both the event_raw sequence
 * and the data.data keys are in ALPHABETICAL order, never insertion order.
 *
 * HTTP (poll_listen, JsonApiHandlerHttp.cpp:388-426 + PollListenner.cpp):
 * the very same event object, but in a flat array with no msg/data envelope:
 *
 *   {"success":"true","events":[ {event_raw,type,type_str,data}, ... ]}
 *
 * ---------------------------------------------------------------------------
 * DELIVERY IS ASYNCHRONOUS, AND THAT IS THE MAIN TRAP OF THIS FILE
 * ---------------------------------------------------------------------------
 * EventManager::appendEvent() (EventManager.cpp:36-59) pushes into a queue and
 * arms an Idler. newEvent.emit() runs INSIDE the idler callback, so an event is
 * emitted AT FLUSH TIME, NOT AT QUEUE TIME. Consequences, all pinned below:
 *   - nothing at all is delivered until pumpEventLoop() runs the uv loop,
 *   - a session created AFTER the event was queued still receives it,
 *   - destroying an HttpTestRequest pumps the loop (harness trap 1) and
 *     therefore silently delivers the backlog,
 *   - a session destroyed before the flush receives nothing and the flush does
 *     not care (JsonApiHandlerWS's destructor disconnects).
 *
 * ---------------------------------------------------------------------------
 * COVERAGE OF THE 23 TYPES - honestly
 * ---------------------------------------------------------------------------
 * 24 enum constants, 23 real types (EventUnkown is dropped by appendEvent),
 * 19 of which production code actually emits. EveryEmittedTypeHasItsEnvelope
 * golden-pins all 19 with non-trivial parameters TRANSCRIBED KEY BY KEY from
 * the production call sites - every one of the 19, audio included, was read
 * off the source rather than guessed, and the call site is quoted next to each
 * create() in that case.
 *
 * What that golden is and is not opposable on, stated exactly: the envelope,
 * the 19 numbers, the 19 type_str, the url encoding and the stringification
 * are opposable for all 19. The PAYLOAD shapes are opposable only for the
 * seven types raised through production code below; for the twelve simulated
 * ones they are documentation verified against the source. Renaming a key
 * inside Squeezebox.cpp would not turn this suite red - but the golden no
 * longer asserts a FALSE shape, which matters because E4.1 reads these files
 * as the reference and would otherwise have "fixed" production to match an
 * invented key.
 *
 * SEVEN of the 19 are additionally raised THROUGH REAL PRODUCTION CODE here,
 * never by the test calling EventManager::create() itself:
 *   io_added          ListeRoom::createIO()           (ListeRoom.cpp:466)
 *   io_deleted        Room::RemoveIO(), two paths     (Room.cpp:77)
 *   io_changed        Internal::set_value() through the real set_state
 *                     command, on the three variable types, AND
 *                     JsonApi::buildJsonSetParam()    (JsonApi.cpp:696)
 *   io_prop_deleted   JsonApi::buildJsonDelParam()    (JsonApi.cpp:726)
 *   room_changed      the four Room:: mutators        (Room.cpp:114-148)
 *   timerange_changed JsonApi::buildJsonSetTimerange()(JsonApi.cpp:1637)
 *   touchscreen_camera_request
 *                     ActionTouchscreen::Execute(), on an action built by
 *                     the real RulesFactory from XML (ActionTouchscreen.cpp:49)
 *
 * The remaining TWELVE are raised through EventManager::create() only, and
 * saying so plainly is better than pretending otherwise:
 *   - scenario_added / scenario_deleted / scenario_changed need a complete
 *     autoscenario staged (Scenario IO + AutoScenario + its rules), which is
 *     E4.0c's setup, not this file's. buildJsonSetTimerange() would raise
 *     scenario_changed as well, but only for an InPlageHoraire that HAS an
 *     auto scenario attached, and the one built here deliberately has none -
 *     which is why TimeRangeChangedOnSetTimerange asserts exactly two
 *     messages and not three.
 *   - the eight audio types come out of Squeezebox's or RoonPlayer's socket
 *     callbacks (Audio/Squeezebox.cpp:268-349, Audio/RoonPlayer.cpp:276-310):
 *     both need a live network peer, and Squeezebox is not even linked into
 *     the core tests.
 *   - io_status_changed comes only from MqttCtrl's subscription callbacks
 *     (IO/Mqtt/MqttCtrl.cpp:625-789), which needs a broker and is not linked.
 * EventManager::create() IS the production entry point all twelve call sites
 * use, so the envelope, the numbering and the parameter shapes are real;
 * only the TRIGGER is simulated. Nothing downstream of create() is faked.
 *
 * FOUR TYPES ARE DEAD - declared, named by typeToString(), never emitted:
 *   EventRoomAdded (5) "room_added", EventRoomDeleted (6) "room_deleted",
 *   EventRoomPropertyDelete (8) "room_prop_deleted",
 *   EventPushNotification (22) "push_notif".
 * A FIFTH IS DEAD IN PRACTICE, by unreachable branch rather than by absence:
 * EventAudioPlaylistCleared ("playlist_cleared") has exactly one create() call
 * site, Squeezebox.cpp:306-313, guarded by `else if (p["2"] == "clear")`. But
 * "clear" is already consumed four branches earlier, at :290
 * (`loadtracks || clear || play || load` -> EventAudioPlaylistReload), so the
 * later branch can never be entered. RoonPlayer never raises it either.
 * A Squeezebox "playlist clear" therefore reports playlist_reload, and
 * playlist_cleared never reaches a client. Its envelope stays in the catalog
 * golden - the constant, the number 18 and the string are still protocol that
 * E4.1 must not renumber - but nothing in the tree can produce it. Reported,
 * not fixed.
 *
 * Measured by grepping every EventManager::create() call site in src/. Adding
 * or deleting a room raises nothing at all (ListeRoom::Add()/Remove() are
 * silent); "push_notif" exists only as a HistLogger tag, ActionPush.cpp:105
 * assigns CalaosEvent::EventPushNotification to a HistEvent::event_type and
 * never calls EventManager::create(). Their STRINGS are still pinned below,
 * because a client that hardcoded them must keep seeing the same numbering.
 *
 * ---------------------------------------------------------------------------
 * FINDINGS - pinned as they are, NOT fixed (E4.0 touches no production line)
 * ---------------------------------------------------------------------------
 *  - poll_listen with an unknown "type" answers {} - an empty JSON object with
 *    no "success" member at all (JsonApiHandlerHttp.cpp:390-426 has no else).
 *    A fourth, undocumented sub-action by omission. It is a 200 OK and the
 *    connection stays open, so the caller cannot tell it did nothing.
 *  - poll_listen reads "type" and "uuid" FROM THE ROOT of the request, like
 *    every other HTTP action. The same document shaped the websocket way (its
 *    arguments under "data") registers nothing and answers {} - the third
 *    perimeter on which this WS/HTTP asymmetry shows up, after E4.0b's
 *    get_io/get_state and E4.0c's autoscenario.
 *  - ELEVEN OF THE 23 type_str VALUES CANNOT BE GUESSED FROM THE C++ CONSTANT.
 *    typeToString() is a hand written table: EventTimeRangeChanged emits
 *    "timerange_changed" (not time_range_changed), the five EventAudioPlaylist*
 *    constants drop the audio prefix and emit "playlist_tracks_added" /
 *    "_deleted" / "_moved" / "playlist_reload" / "playlist_cleared",
 *    EventTouchScreenCamera gains a suffix and emits
 *    "touchscreen_camera_request", EventPushNotification is truncated to
 *    "push_notif", the two *PropertyDelete become "*_prop_deleted", and
 *    EventUnkown is misspelled. TypeStrDoesNotFollowTheEnumName spells all
 *    eleven out, because a test written from the constant name would assert a
 *    string nothing ever emits and still pass.
 *  - typeToString() answers the misspelled "unkown" for any unmapped integer,
 *    and EventUnkown itself maps to it.
 *  - docs/08_http_api.md:210-221 documents an event envelope the code has
 *    never emitted ({"type":"io_changed","id":..,"value":..}) and lists a type
 *    name "push_notification" that does not exist (the code says "push_notif").
 *    The documentation cannot be used as an oracle; these cases are the oracle.
 *  - a service-scoped session (login_service, the MCP sidecar) receives EVERY
 *    event: handleEvents() only tests loggedin, never serviceScope, so the
 *    whole scope restriction of the request/response path has no equivalent on
 *    the push path.
 *  - LOADING A CONFIGURATION IS SILENT. JsonApiCharacterization.h:481-483 and
 *    JsonApiCharacterization.cpp:741-748 both state that loading a house
 *    raises one EventIOAdded per IO. MEASURED: it raises NOTHING.
 *    EventIOAdded is emitted by ListeRoom::createIO() (ListeRoom.cpp:466), the
 *    runtime path of the JSON API; Config loading goes through
 *    Room::LoadFromXml() (Room.cpp:152-175), which builds and attaches the IOs
 *    without a word. What DOES fill the queue - and what E4.0a actually saw -
 *    is the OPPOSITE end: clearCoreState() destroys the rooms, ~Room() calls
 *    RemoveIO() per IO, and each one raises EventIODeleted (Room.cpp:77).
 *    Those land in the queue at the very end of a case, after the fixture
 *    pumped, and leak into the next one. Both halves are pinned below
 *    (LoadingAHouseFromConfigRaisesNoEventAtAll,
 *    DroppingTheHouseRaisesOneIoDeletedPerIo) and this fixture drains once
 *    more at the start of SetUp() because of the second.
 ******************************************************************************/

