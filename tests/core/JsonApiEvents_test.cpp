    EXPECT_EQ(6, static_cast<int>(CalaosEvent::EventRoomDeleted));
    EXPECT_EQ(8, static_cast<int>(CalaosEvent::EventRoomPropertyDelete));
    EXPECT_EQ(22, static_cast<int>(CalaosEvent::EventPushNotification));

