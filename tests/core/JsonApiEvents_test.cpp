TEST_F(JsonApiEventsTest, TypeStrDoesNotFollowTheEnumName)
{
    //ELEVEN OF THE 23 WIRE NAMES CANNOT BE DERIVED FROM THE C++ CONSTANT.
    //typeToString() is a hand written table (EventManager.cpp:141-183), not a
    //transliteration, and anyone who guesses the string from the enum gets it
    //wrong half the time - while writing a test that still passes, because it
    //would assert the wrong string for an event the case never actually
    //raises. Each divergence is spelled out here so the trap is visible.
    struct { int type; const char *wire; const char *whyItSurprises; } cases[] = {
        //Property -> prop, Delete -> deleted
        { CalaosEvent::EventIOPropertyDelete,     "io_prop_deleted",           "Property/Delete abbreviated and re-tensed" },
        { CalaosEvent::EventRoomPropertyDelete,   "room_prop_deleted",         "same, on the dead room variant" },
        //TimeRange collapses to one word
        { CalaosEvent::EventTimeRangeChanged,     "timerange_changed",         "TimeRange -> timerange, NOT time_range" },
        //The five playlist events drop "audio" and rename the verb
        { CalaosEvent::EventAudioPlaylistAdd,     "playlist_tracks_added",     "loses the Audio prefix, gains tracks_" },
        { CalaosEvent::EventAudioPlaylistDelete,  "playlist_tracks_deleted",   "loses the Audio prefix, gains tracks_" },
        { CalaosEvent::EventAudioPlaylistMove,    "playlist_tracks_moved",     "loses the Audio prefix, gains tracks_" },
        { CalaosEvent::EventAudioPlaylistReload,  "playlist_reload",           "loses the Audio prefix, keeps the verb" },
        { CalaosEvent::EventAudioPlaylistCleared, "playlist_cleared",          "loses the Audio prefix, keeps the verb" },
        //A suffix that exists nowhere in the constant
        { CalaosEvent::EventTouchScreenCamera,    "touchscreen_camera_request", "gains a _request suffix" },
        //Truncated
        { CalaosEvent::EventPushNotification,     "push_notif",                "truncated; docs say push_notification, which is WRONG" },
        //And the typo
        { CalaosEvent::EventUnkown,               "unkown",                    "misspelled in production" },
    };

    for (const auto &c: cases)
        EXPECT_EQ(c.wire, CalaosEvent::typeToString(c.type))
                << "type " << c.type << " (" << c.whyItSurprises << ")";
}

