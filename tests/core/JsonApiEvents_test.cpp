class JsonApiEventsTest: public JsonApiCharacterizationTest
{
protected:
    void SetUp() override
    {
        JsonApiCharacterizationTest::SetUp();
        forgetIOState(EV_EXTRA_IO);
        forgetIOState(EV_DOOMED_IO);
        forgetIOState(EV_PLAGE);

        //ORDER INDEPENDENCE, and it is not optional here. CoreFixture's
        //TearDown() destroys the rooms, ~Room() raises one EventIODeleted per
        //IO it still owns, and those are queued AFTER the parent TearDown()
        //already pumped. They would otherwise be delivered to the first
        //session of the NEXT case - which passes alone and fails under
        //--gtest_shuffle. Drain the inherited backlog before anything else.
        pumpEventLoop();
    }

    void TearDown() override
    {
        //A PollObject holds a live 300s Timer and stays connected to
        //EventManager::newEvent for the whole process. Leaking one would make
        //every later case of this binary feed a stranger's queue.
        for (const std::string &uuid: registeredPolls)
            PollListenner::Instance().Unregister(uuid);
        registeredPolls.clear();

        JsonApiCharacterizationTest::TearDown();
    }

    /* ---------------------------------------------------------------------
     * Event helpers
     * ------------------------------------------------------------------ */

    //Queue one event and flush it. Split on purpose from the cases that pin
    //the ABSENCE of a flush.
    static void raise(int type, Params p)
    {
        EventManager::create(type, p);
        pumpEventLoop();
    }

    //The "data" member of every message of a session, i.e. the list of event
    //objects it received, in delivery order.
    static Json receivedEvents(const WsTestSession &ws)
    {
        Json arr = Json::array();
        for (const std::string &m: ws.messages())
        {
            const Json env = asJsonDocument(m);
            if (env.is_object() && str(env, "msg") == "event")
                arr.push_back(member(env, "data"));
        }
        return arr;
    }

    //Every message of a session, envelope included.
    static Json receivedEnvelopes(const WsTestSession &ws)
    {
        Json arr = Json::array();
        for (const std::string &m: ws.messages())
            arr.push_back(asJsonDocument(m));
        return arr;
    }

    /* member() and str() used to live here. They are now CalaosTest::member()
     * and CalaosTest::str() in JsonApiCharacterization.h, promoted to a rule of
     * the series after this ticket measured what operator[] does to a run when
     * a key moves. Read the block above their declaration before reaching for
     * operator[] on a captured payload.
     */

    //Fails on the first leaf that is not a JSON string. The entire event path
    //is stringified today (CalaosEvent::toJson() uses json_pack "s" for the
    //three scalars and Params::toJson() emits json_string only): a migration
    //that turned "type" into a number, or a numeric looking parameter into a
    //double, must break something here.
    static ::testing::AssertionResult everyLeafIsAString(const Json &j,
                                                         const std::string &path = "")
    {
        if (j.is_object())
        {
            for (auto it = j.begin(); it != j.end(); ++it)
            {
                auto r = everyLeafIsAString(it.value(), path + "/" + it.key());
                if (!r) return r;
            }
            return ::testing::AssertionSuccess();
        }
        if (j.is_array())
        {
            for (size_t i = 0; i < j.size(); i++)
            {
                auto r = everyLeafIsAString(j[i], path + "/" + std::to_string(i));
                if (!r) return r;
            }
            return ::testing::AssertionSuccess();
        }
        if (j.is_string())
            return ::testing::AssertionSuccess();

        return ::testing::AssertionFailure()
                << "non string leaf at " << path << ": " << j.dump();
    }

    /* ---------------------------------------------------------------------
     * poll_listen helpers
     *
     * Every one of them builds and destroys an HttpTestRequest, and the
     * destructor pumps the loop (harness trap 1). That is why the cases below
     * always pump EXPLICITLY where they mean to flush, instead of relying on
     * where a request happens to go out of scope.
     * ------------------------------------------------------------------ */

    std::string pollRegister()
    {
        HttpTestRequest req;
        req.send(authenticated(Json{{ "action", "poll_listen" },
                                    { "type", "register" }}));
        const Json body = req.bodyJson();
        const std::string uuid = body.is_object()? body.value("uuid", std::string())
                                                 : std::string();
        if (!uuid.empty())
            registeredPolls.push_back(uuid);
        return uuid;
    }

    static Json pollGet(const std::string &uuid)
    {
        HttpTestRequest req;
        req.send(authenticated(Json{{ "action", "poll_listen" },
                                    { "type", "get" },
                                    { "uuid", uuid }}));
        return req.bodyJson();
    }

    static Json pollUnregister(const std::string &uuid)
    {
        HttpTestRequest req;
        req.send(authenticated(Json{{ "action", "poll_listen" },
                                    { "type", "unregister" },
                                    { "uuid", uuid }}));
        return req.bodyJson();
    }

    std::vector<std::string> registeredPolls;
};

