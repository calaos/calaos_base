/*******************************************************************************
 * E4.0e - session, envelopes and error paths: everything of the JSON API that
 * is NOT a data payload.
 *
 *      login   login_service   settings/change_cred   register_push
 *      get_mcp_info            eventlog               config/get
 *
 * plus every error path of both transports: the EIGHT scope refusals (E4.6e
 * added autoscenario), the "unknown action", "unkown audio_action" and
 * "unknown autoscenario type" answers, the silences (camera, settings, unknown
 * msg, not logged in), the HTTP 400 on
 * a rejected login, the HTTP 404 of event_picture, the JSON error paths of the
 * six binary (image/jpeg) operations, and the migration traps of E4.0.md:
 * invalid UTF-8, empty strings, very large integers, absent members,
 * unexpected types.
 *
 * Everything goes through the E4.0a harness (tests/core/JsonApiCharacterization.h
 * - read it first): semantic oracle, one golden per case, goldens GENERATED by
 * CALAOS_GOLDEN_UPDATE=1 and never hand written. The only byte exact
 * comparisons here are on HTTP status lines, HTTP header values and HTML error
 * bodies, which are not JSON (precedent: T3.17d).
 *
 * ---------------------------------------------------------------------------
 * THE HEADLINE FINDING: E4.0.md IS WRONG ABOUT INVALID UTF-8
 * ---------------------------------------------------------------------------
 * E4.0.md:308 states that invalid UTF-8 in a name or param makes json_dumps()
 * return NULL, which makes the HTTP transport answer 500 and close. MEASURED
 * HERE, AND IT IS NOT WHAT HAPPENS.
 *
 * jansson refuses invalid UTF-8 at CONSTRUCTION time, long before dumping:
 * json_string() answers NULL on an invalid byte sequence, and
 * json_object_set_new() answers -1 both on a NULL value and on an invalid key.
 * Neither return code is checked anywhere in JsonApi.cpp or Params::toJson().
 * So an invalid byte sequence does not produce a 500: THE KEY (or the whole
 * pair) IS SILENTLY DROPPED FROM THE ANSWER, and the client gets a 200 with a
 * payload that is missing a member. The cases named
 * InvalidUtf8*  below pin exactly that.
 *
 * The consequence for E4.1 is the opposite of the one the plan expected, and
 * strictly worse:
 *   - today  : invalid UTF-8 -> member silently missing, 200 OK.
 *   - nlohmann: `j[key] = value` stores the bytes without complaining, and the
 *     failure is deferred to dump(), which THROWS type_error.316. Nothing on
 *     either transport catches it (JsonApiHandlerHttp::sendJson() and
 *     JsonApiHandlerWS::sendJson() call dump() bare), so the server calls
 *     std::terminate.
 * A silently truncated answer becomes a process abort. The 500 path the plan
 * wanted to preserve does not exist to begin with: with the builders as they
 * are, json_dumps() can only fail on a NULL root, and no builder returns NULL
 * (buildJsonStatusInfo() is the only one that can, and its caller guards it).
 * Utf8Trap_NlohmannDumpThrowsWhereJanssonDrops states the difference on the two
 * libraries directly, so E4.1 cannot miss it.
 *
 * The injection channel is real, not hypothetical: the HTTP transport falls
 * back to the GET parameters whenever the body is not JSON
 * (JsonApiHandlerHttp.cpp:81-92), and those come from the query string, which
 * HfURISyntax::getQuery() PERCENT-DECODES before HttpClient splits it
 * (hef_uri_syntax.cpp:363-368, HttpClient.cpp:337-347). So "?param=%ff%80x" is
 * all it takes to put arbitrary bytes into a Params, and from there into a key
 * or a value of an answer. The JSON body itself cannot carry invalid UTF-8,
 * jansson's parser rejects the whole document.
 *
 * ---------------------------------------------------------------------------
 * FROZEN BUGS AND DIVERGENCES - pinned as they are, DO NOT FIX HERE
 * ---------------------------------------------------------------------------
 *  - eventlog with per_page="0" or with any NON EMPTY non numeric per_page
 *    DIVIDES BY ZERO and kills the server. A failed non empty extraction
 *    writes 0 into the destination (C++11 operator>>), so the perPage=100
 *    default of JsonApi.cpp:2010 is overwritten by the very next line, and
 *    HistLogger.cpp:268 computes `rowcount / ac->per_page` in the sqlite worker
 *    thread: SIGFPE, from any authenticated client, on both transports. An
 *    ABSENT or EMPTY per_page is harmless, the sentry fails before anything is
 *    written and the 100 survives. NOT exercised here on purpose - the signal
 *    would take the whole test binary with it. The helper is pinned instead
 *    (FromStringWritesZeroOnFailure...), so the trace is in the suite, and
 *    every eventlog case below sends an explicit numeric per_page.
 *  - the "unkown audio_action" and "unkown camera id" error strings are
 *    misspelled in production, on both transports.
 *  - autoscenario with an unknown or absent type ANSWERS AN ERROR since E4.6e,
 *    on both transports. It used to be silent, and over HTTP not even to close
 *    the connection - the client hung until its own timeout.
 *  - processCamera() with a KNOWN camera id and an unknown "type" is silent for
 *    the same reason (no else branch), while an unknown id does answer.
 *  - settings with an unknown or absent "action" is silent too.
 *  - get_mcp_info is HTTP only. docs/08_http_api.md:281 announces it as "HTTP
 *    or WS"; over WS it is silently ignored.
 *  - login_service never grants access while mcp_service_token is unset, but
 *    the refusal it sends is indistinguishable from a wrong token
 *    ({"success":"false","error":"invalid token"}).
 *  - a single failed login blocks the ip for BaseDelay=1s, and the blocked
 *    answer is byte identical to the wrong credentials answer on both
 *    transports.
 *  - E4.0.md:349 says "les 8 refus scopeDenied". There are SEVEN
 *    (JsonApiHandlerWS.cpp:177, :182, :195, :202, :209, :214, :219), and the
 *    HTTP transport has no scope notion at all.
 ******************************************************************************/

