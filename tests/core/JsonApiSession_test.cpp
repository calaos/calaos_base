class JsonApiSessionTest: public JsonApiCharacterizationTest
{
protected:
    void SetUp() override
    {
        //MUST run before CoreFixture::SetUp() installs the per-case directories.
        ensureHistLogger();

        JsonApiCharacterizationTest::SetUp();

        //NO DRAIN HERE ANY MORE. This SetUp() used to pump once to absorb the
        //EventIODeleted that the PREVIOUS case's clearCoreState() left in the
        //idler - two silence cases of this file had been MEASURED failing with
        //ws.count()==8 depending only on what ran before them. E4.0g moved the
        //fixture's pump after CoreFixture::TearDown(), so those events are
        //drained where they are produced and every case starts on an empty
        //queue. ensureHistLogger() above stays: it solves an unrelated problem
        //(the HistLogger singleton captures its base path in its constructor).

        //Deterministic MCP tokens for get_mcp_info and login_service, whatever
        //order the cases run in (--gtest_shuffle). See ensureMcpTokens().
        ensureMcpTokens();
    }

    /***************************************************************************
     * The history database has to outlive the cases.
     *
     * HistLogger is a Meyers singleton whose CONSTRUCTOR captures
     * Utils::getCacheFile("events.db") and spawns a worker thread that opens
     * that file with sqlite. CoreFixture gives every case a private
     * <tmp>/calaos_coretest_XXXXXX tree and `rm -rf`s it in TearDown, so a
     * singleton born inside a case points at a directory that is deleted a few
     * milliseconds later. MEASURED: the worker then throws
     * sqlite::errors::cantopen OUTSIDE its try block (HistLogger.cpp:189) and
     * std::terminate takes the whole binary down - and even if the open won the
     * race, sqlite could no longer create its journal next to a deleted file.
     *
     * So the singleton is built HERE, once, against a directory that belongs to
     * this test file and lives as long as the process. The wait is not
     * cosmetic: it is what proves the worker really opened the database before
     * the first case replaces the cache path under it.
     **************************************************************************/
    static void ensureHistLogger()
    {
        static bool done = false;
        if (done)
            return;
        done = true;

        static char tmpl[] = "/tmp/calaos_e40e_hist_XXXXXX";
        ASSERT_TRUE(::mkdtemp(tmpl) != nullptr)
                << "could not create the history database directory";

        const std::string base = tmpl;
        const std::string conf = base + "/config";
        const std::string cache = base + "/cache";
        ASSERT_EQ(0, ::mkdir(conf.c_str(), 0755));
        ASSERT_EQ(0, ::mkdir(cache.c_str(), 0755));

        std::vector<char> c(conf.begin(), conf.end());
        c.push_back('\0');
        std::vector<char> k(cache.begin(), cache.end());
        k.push_back('\0');
        Utils::initConfigOptions(c.data(), k.data(), true);

        //Round trip through the worker thread: it only answers once the
        //database is open and the two tables exist.
        auto opened = std::make_shared<bool>(false);
        HistLogger::Instance().getEvents(0, 100,
                [opened](bool, string, const vector<HistEvent> &, int, int)
        {
            *opened = true;
        });
        waitUntil([opened]() { return *opened; });
        ASSERT_TRUE(*opened) << "the history database never opened";

        ::atexit([]()
        {
            const std::string cmd = std::string("rm -rf '") + tmpl + "'";
            if (::system(cmd.c_str()) != 0) {}
        });
    }

    /***************************************************************************
     * Total accessors. nlohmann's const operator[] asserts on a missing key,
     * which ABORTS the whole run at the first moved key instead of reporting
     * it - measured in E4.0d, where a mutated binary died on case 5 out of 33.
     * Everything below reads members through these two, so a mutation produces
     * a readable list of failures.
     **************************************************************************/
    static Json member(const Json &j, const std::string &key)
    {
        if (!j.is_object())
            return Json();
        auto it = j.find(key);
        if (it == j.end())
            return Json();
        return *it;
    }

    static std::string str(const Json &j, const std::string &key)
    {
        const Json v = member(j, key);
        return v.is_string()? v.get<std::string>(): std::string();
    }

    static bool has(const Json &j, const std::string &key)
    {
        return j.is_object() && j.find(key) != j.end();
    }

    /***************************************************************************
     * The MCP tokens.
     *
     * McpServerManager caches both tokens in members filled by the private
     * ensureTokens(), which only start() calls. Left alone they stay EMPTY, so
     * get_mcp_info would answer an empty token and login_service could never
     * succeed (JsonApiHandlerWS.cpp:546 refuses on an empty expected token).
     *
     * start() is safe to call here: it reads the two config options (set to
     * fixed values just below, so no random token is generated), unlinks a
     * socket path, and then spawnSidecar() stat()s
     * Prefix::binDirectoryGet()/calaos_mcp and RETURNS SILENTLY when it does not
     * exist (McpServerManager.cpp:180-187). CALAOS_BIN_PREFIX is pointed at a
     * directory that cannot exist, so no process is ever spawned and make check
     * stays hermetic.
     *
     * It runs exactly once per process (start() is guarded by `started`), hence
     * the static flag: the tokens are then identical for every case whatever
     * the shuffle order.
     **************************************************************************/
    static const char *mcpBearerToken() { return "e40e-bearer-token"; }
    static const char *mcpServiceToken() { return "e40e-service-token"; }

    static void ensureMcpTokens()
    {
        static bool done = false;

        //The config is rebuilt by the fixture on every case, so the options
        //have to be re-set even once the singleton is primed - a case reading
        //them back from the config (config/get) must see them too.
        Utils::set_config_option("mcp_token", mcpBearerToken());
        Utils::set_config_option("mcp_service_token", mcpServiceToken());

        if (done)
            return;
        done = true;

        ::setenv("CALAOS_BIN_PREFIX", "/nonexistent/e40e/bin", 1);
        McpServerManager::Instance().start();
    }

    /***************************************************************************
     * Loop pumping with a deadline. eventlog is the only command of this file
     * that answers ASYNCHRONOUSLY: HistLogger pushes the query to its sqlite
     * worker thread and wakes the main loop back up through a uvw AsyncHandle
     * (HistLogger.cpp:128-143). Nothing arrives without pumping.
     *
     * The 2s bound is deliberate and well under the 30s read timeout Timer
     * HttpClient's constructor installs (trap 2 of the harness header): an
     * HttpTestRequest can safely be held alive across one of these waits.
     **************************************************************************/
    static bool waitUntil(const std::function<bool()> &done)
    {
        for (int i = 0;i < 400;i++)
        {
            if (done())
                return true;
            pumpEventLoop(1);
            std::this_thread::sleep_for(std::chrono::milliseconds(5));
        }
        return done();
    }

    /***************************************************************************
     * The event log fixture.
     *
     * The events table has to be NON EMPTY, and with a row count that is not a
     * multiple of per_page, otherwise total_page and total_count carry the same
     * value in every golden and SWAPPING THE TWO KEYS IN PRODUCTION WOULD LEAVE
     * THE SUITE GREEN. That is the exact failure mode E4.0b and E4.0c were
     * caught on. Five rows read two at a time give total_count=5,
     * total_page=3, page=0, per_page=2: four distinct values for four keys.
     *
     * Seeded once per process for the same reason as the MCP tokens: the sqlite
     * database is opened once, by whichever case reaches HistLogger first, and
     * it is never emptied. A per case seed would make the counters depend on
     * the shuffle order.
     *
     * created_at is generated by sqlite (CURRENT_TIMESTAMP, one second
     * resolution) so the event objects themselves are NOT golden material and
     * their order is not stable; the cases assert their shape and let the
     * goldens cover the deterministic error payloads.
     *
     * REVIEW FINDING R1, and the reason seededUuids() exists: "id" and
     * "created_at" are BOTH non deterministic strings, so asserting is_string()
     * on each of them left the pair interchangeable - swapping the two VALUES in
     * HistEvent::toJson() (HistLogger.cpp:85 and :90) kept the suite 102/102
     * green. The seeded uuids are therefore remembered here so the case can
     * assert that "id" holds ONE OF THEM and that "created_at" holds none of
     * them, which is what actually pins the mapping. HistEvent::toJson() is
     * rewritten wholesale by E4.1, so this pair sits right in the blast radius
     * of the change this series exists to guard.
     **************************************************************************/
    static int seededEventCount() { return 5; }

    //The uuids seedEventLog() generated, in insertion order.
    static std::vector<std::string> &seededUuids()
    {
        static std::vector<std::string> uuids;
        return uuids;
    }

    static bool isSeededUuid(const std::string &s)
    {
        const auto &u = seededUuids();
        return std::find(u.begin(), u.end(), s) != u.end();
    }

    static void seedEventLog()
    {
        static bool done = false;
        if (done)
            return;
        done = true;

        for (int i = 0;i < seededEventCount();i++)
        {
            HistEvent e = HistEvent::create();
            seededUuids().push_back(e.uuid);
            e.event_type = CalaosEvent::EventIOChanged;
            e.io_id = "e40e_logged_io_" + Utils::to_string(i);
            e.io_state = (i % 2)? "true": "false";
            e.pic_uid = "e40e_pic_" + Utils::to_string(i);
            //event_raw is stored as TEXT but HistEvent::toJson() PARSES it back
            //(HistLogger.cpp:93-100), so it is a nested object on the wire and
            //not a string. A non parsable value falls back to {}.
            e.event_raw = "{\"type_str\":\"io_changed\",\"data\":{\"id\":\"" +
                          e.io_id + "\"}}";
            HistLogger::Instance().appendEvent(e);
        }

        //Wait for the worker thread to have committed all of them, otherwise
        //the first case to read would see a partial table. The result is held
        //in a shared_ptr, not captured by reference: if a query ever timed out,
        //its callback would still be alive inside the uvw AsyncHandle and would
        //fire during a later pump.
        int seen = 0;
        for (int attempt = 0;attempt < 20 && seen < seededEventCount();attempt++)
        {
            auto state = std::make_shared<std::pair<bool, int>>(false, 0);
            HistLogger::Instance().getEvents(0, 100,
                    [state](bool success, string, const vector<HistEvent> &,
                            int, int total_count)
            {
                state->first = true;
                if (success)
                    state->second = total_count;
            });

            waitUntil([state]() { return state->first; });
            seen = state->second;
        }

        ASSERT_GE(seen, seededEventCount())
                << "the event log could not be seeded, every eventlog case below "
                   "would characterize an empty database";
    }

    //Sends an eventlog request over WS and pumps until the async answer lands.
    static Json wsEventLog(WsTestSession &ws, Json data)
    {
        ws.clear();
        ws.send(Json{{ "msg", "eventlog" }, { "msg_id", "ev" }, { "data", data }});
        waitUntil([&]() { return ws.count() > 0; });
        return ws.lastData();
    }
};

/*******************************************************************************
 * The websocket envelope
 *
 * {msg, msg_id, data}. msg_id is OMITTED, never null, when the client sent
 * none, and data is omitted when the handler passes a null document. The tree
 * builds this envelope through TWO different sendJson() overloads which insert
 * the keys in two different orders - the semantic oracle is blind to that on
 * purpose (E4.0.md, "L'oracle").
 ******************************************************************************/

TEST_F(JsonApiSessionTest, WsEnvelopeCarriesMsgMsgIdAndData)
{
    WsTestSession ws(false);
    ws.send(Json{{ "msg", "login" }, { "msg_id", "e40e-1" },
                 { "data", {{ "cn_user", apiUser() }, { "cn_pass", apiPassword() }} }});

    ASSERT_EQ(1u, ws.count());
    EXPECT_JSON_GOLDEN("e40e_ws_login_success", ws.lastEnvelope());

    const Json env = ws.lastEnvelope();
    EXPECT_EQ("login", str(env, "msg"));
    EXPECT_EQ("e40e-1", str(env, "msg_id"));
    EXPECT_TRUE(has(env, "data"));
}

