//Parse helper. Throws nothing: on a parse error the returned json is discarded
//by the assertion, which reports the error itself.
bool parseJsonText(const std::string &text, Json &out, std::string &error);

//Returns "" when the two documents are semantically equal, otherwise a human
//readable description of the FIRST diverging node, prefixed by its JSON
//pointer path (e.g. "/home/2/items/5/state: expected ... actual ...").
std::string firstJsonDifference(const Json &expected, const Json &actual);

//Normalisation overloads, so the assertions below accept either a raw JSON
//text (the common case: a captured payload or a golden file) or an already
//built Json. Note that these are deliberately NOT implicit conversions: a
//std::string implicitly converted to Json would silently become a JSON
//*string* and turn the assertion into the string comparison this harness
//forbids.
inline const Json &asJsonDocument(const Json &j) { return j; }
Json asJsonDocument(const std::string &text);
inline Json asJsonDocument(const char *text) { return asJsonDocument(std::string(text)); }

template<typename Expected, typename Actual>
::testing::AssertionResult jsonSemanticEqual(const char *expectedExpr,
                                            const char *actualExpr,
                                            const Expected &expected,
                                            const Actual &actual)
{
    const Json jexpected = asJsonDocument(expected);
    const Json jactual = asJsonDocument(actual);

    //asJsonDocument() answers a discarded value on a parse error
    if (jexpected.is_discarded())
        return ::testing::AssertionFailure()
                << expectedExpr << " is not parsable JSON";
    if (jactual.is_discarded())
        return ::testing::AssertionFailure()
                << actualExpr << " is not parsable JSON";

    const std::string diff = firstJsonDifference(jexpected, jactual);
    if (diff.empty())
        return ::testing::AssertionSuccess();

    return ::testing::AssertionFailure()
            << "JSON documents differ (semantic comparison, key order ignored,\n"
            << "array order significant, types strict).\n"
            << "  expected: " << expectedExpr << "\n"
            << "  actual  : " << actualExpr << "\n"
            << "  " << diff << "\n"
            << "--- expected ---\n" << jexpected.dump(2) << "\n"
            << "--- actual ---\n" << jactual.dump(2);
}

