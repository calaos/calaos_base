/*******************************************************************************
 * E4.0a - Characterization harness for the JSON API (port 5454).
 *
 * READ THIS BEFORE WRITING A SINGLE ASSERTION. Sub-tickets E4.0b..E4.0f are
 * expected to use this file and nothing else as their entry point; you should
 * not need to read JsonApiCharacterization.cpp to use it.
 *
 * ---------------------------------------------------------------------------
 * WHAT THIS IS FOR
 * ---------------------------------------------------------------------------
 * Freezing the OBSERVABLE behaviour of the JSON API before the jansson ->
 * nlohmann migration (E4.1). It records what the code does TODAY, bugs
 * included. It fixes nothing, it improves nothing. If a test here looks like
 * it pins a bug, it does, on purpose (see "KNOWN DIVERGENCES" below).
 *
 * ---------------------------------------------------------------------------
 * THE ORACLE - NON NEGOTIABLE
 * ---------------------------------------------------------------------------
 * Comparison is SEMANTIC: both sides are parsed with nlohmann::json::parse()
 * and compared with operator==. Consequences, all of them wanted:
 *
 *   - INSENSITIVE to key order, by construction (a nlohmann object is a
 *     std::map). jansson preserves insertion order, nlohmann sorts keys, and
 *     the user has ALREADY accepted that change of order. The tree even emits
 *     the WS envelope in two different key orders today depending on which
 *     sendJson() overload is used (JsonApiHandlerWS.cpp:63-73 gives
 *     msg,msg_id,data; :75-85 gives data,msg,msg_id) - clients already live
 *     with both. ⚠️ E4.1s DELETED the jansson overload: one envelope order is
 *     left, the sorted one, plus the no-data envelope of sendJsonNoData(),
 *     which OMITS the key rather than writing a null.
 *   - SENSITIVE to array order. The order of rooms, IOs and rules IS
 *     semantic (it drives evaluation order, invariant of the E4.2 series).
 *     NEVER sort an array before comparing.
 *   - STRICT on types: "3" != 3. A migration that "improves" a stringified
 *     number into a real JSON number must break the test. That is the point.
 *
 * COMPARING SERIALIZED JSON STRINGS IS FORBIDDEN AND WILL BE REJECTED IN
 * REVIEW. Concretely, never write any of:
 *      EXPECT_EQ(payload, "{\"a\":\"b\"}");
 *      EXPECT_EQ(j.dump(), golden);
 *      EXPECT_EQ(j.dump(-1, ' ', true, Json::error_handler_t::replace), "...");
 *      any assertion on key order or on the length of a JSON string.
 * Use EXPECT_JSON_EQ / ASSERT_JSON_EQ / EXPECT_JSON_GOLDEN below. They accept
 * a raw std::string of JSON text and parse it for you - passing the captured
 * payload straight in is both correct and the shortest thing to write, so
 * there is no reason to hand-roll a string compare.
 *
 * On failure the assertion prints the JSON-pointer path of the FIRST diverging
 * node (e.g. /home/2/items/5/state) with expected and actual. A raw EXPECT_EQ
 * on a 200-key object is unusable and would make the migration miserable.
 *
 * ---------------------------------------------------------------------------
 * GOLDEN FILES
 * ---------------------------------------------------------------------------
 * Stored one per case in tests/core/golden/<name>.json, UTF-8, dump(2).
 * They are GENERATED BY THE CODE, never hand written:
 *
 *      CALAOS_GOLDEN_UPDATE=1 ./core/JsonApiCharacterization_test
 *
 * rewrites every golden the run touches, then you re-read the diff and commit
 * it. A golden that was hand-edited to look "clean" is worthless: it would
 * describe the desirable, not the existing.
 *
 * Goldens are located through, in order: $CALAOS_GOLDEN_DIR, the compile-time
 * -DCALAOS_GOLDEN_DIR passed by tests/Makefile.am, $srcdir/core/golden, then a
 * couple of relative fallbacks. You do not need to care unless you run the
 * binary by hand from an unusual directory.
 *
 * ---------------------------------------------------------------------------
 * THE THREE POINTS E4.0a HAD TO SETTLE, AND HOW THEY WERE SETTLED
 * ---------------------------------------------------------------------------
 * (a) HttpClient::getClientIp() - stub in the test unit, or link the real
 *     HttpClient.o?  MEASURED: `nm -Cu JsonApiHandlerWS.o` shows exactly one
 *     HttpClient symbol needed (getClientIp), so a stub WOULD be enough for a
 *     WS-only binary. But `nm -Cu JsonApiHandlerHttp.o` needs three
 *     (getClientIp, buildHttpResponse, buildHttpResponseFromFile), and
 *     buildHttpResponse() is exactly the production logic E4.0e must
 *     characterize (headers, Content-Length, conn_close). Stubbing it would
 *     characterize the stub. DECISION: LINK the real HttpClient.o and its
 *     closure (the block is already written, tested and green for
 *     core/RemoteUIDeviceInfo_test). No stub anywhere in this harness.
 *
 * (b) JsonApiHandlerHttp needs a non-null HttpClient (sendLoginFailed() and
 *     sendJson() dereference it without a guard). MEASURED: constructing
 *     HttpClient on an UNCONNECTED uvw::TcpHandle works - buildHttpResponse()
 *     is pure string formatting over member state, getClientIp() is null and
 *     exception safe and answers "unknown", and ~HttpClient() does not touch
 *     the socket. So the HTTP transport is characterizable end to end.
 *     CONSTRAINT, carried into the design: buildHttpResponse() MUTATES the
 *     connection state (resHeaders accumulates, conn_close flips,
 *     HttpClient.cpp:552-566), therefore ONE FRESH HttpClient PER REQUEST is
 *     MANDATORY. HttpTestRequest below enforces it: one object, one request,
 *     reuse is refused.
 *
 * (c) Event delivery needs the uvw loop pumped. EventManager::appendEvent()
 *     queues into an Idler (EventManager.cpp:46-54) and CalaosCoreFixture.h
 *     documents that the queue simply grows in tests. MEASURED: a single
 *     uvw::Loop::getDefault()->run<NOWAIT>() is enough to fire the idler and
 *     get the WS "event" envelope out; pumpEventLoop() below runs a few
 *     iterations so the close callbacks of the one-shot idle handle also run.
 *     Asserting right after EventManager::create() without pumping always
 *     sees zero messages. E4.0d owns the event cases; the pump is here.
 *
 * ---------------------------------------------------------------------------
 * TRAPS THIS HARNESS SETS FOR YOU - READ BEFORE DEBUGGING A WEIRD FAILURE
 * ---------------------------------------------------------------------------
 * 1. DESTROYING AN HttpTestRequest FLUSHES THE EVENT QUEUE. Its destructor
 *    calls pumpEventLoop(2) to run the uv close callbacks of the TcpHandle it
 *    allocated. That also fires the EventManager idler. So an HTTP request
 *    going out of scope silently delivers every queued event to every live WS
 *    session. This one is aimed straight at E4.0d: if a case mixes an HTTP
 *    request with an event expectation, scope the request explicitly, or
 *    snapshot ws.count() before and after instead of assuming nothing moved.
 *
 * 2. AN HttpTestRequest KEPT ALIVE ACROSS A LONG PUMP WILL FIRE A TIMER.
 *    HttpClient's constructor (HttpClient.cpp:145-153) installs a LIVE read
 *    timeout Timer whose callback calls CloseConnection() - on a handle that
 *    was never connected. Harmless today because every case here destroys the
 *    request long before the timeout, and pumpEventLoop() only runs a handful
 *    of NOWAIT iterations. A sub-ticket that holds a request across a longer
 *    or repeated pump will trip it. Keep HttpTestRequest objects short lived.
 *
 * 3. PROVING A MUTATION RED REQUIRES DELETING TWO FILES, NOT ONE. Every test
 *    binary in this tree overrides <name>_DEPENDENCIES, which removes the
 *    objects of src/bin/calaos_server from its prerequisites. Rebuilding one
 *    .o therefore does NOT relink the test binary: make answers "is up to
 *    date" and the OLD binary runs again, green. Measured live on this very
 *    binary during E4.0a. So:
 *        rm -f src/bin/calaos_server/<Mutated>.o tests/core/<Your>_test
 *        make -C src/bin/calaos_server <Mutated>.o
 *        make -C tests core/<Your>_test        # must print CXXLD, check it
 *    A mutation proof without both deletions and the CXXLD line in the log is
 *    not a proof, and review rejects it. The same trap will produce a false
 *    green during E4.1 itself, which is the catastrophe this series exists to
 *    prevent.
 *
 * ---------------------------------------------------------------------------
 * KNOWN DIVERGENCES - FREEZE THEM, DO NOT FIX THEM
 * ---------------------------------------------------------------------------
 *   - audio_db expects "get_albums" over HTTP and "get_album" over WS.
 *   - autoscenario with an unknown "type" USED TO answer nothing at all, on
 *     both transports, HTTP not even closing the socket. E4.6e (D8) gave both
 *     dispatchers an else; the divergence is gone and the cases that pinned it
 *     are flipped. Silence is still observable behaviour elsewhere in this
 *     harness: assert the message count is zero.
 *   - buildQuery() tests jParam.Exists("id") but reads jParam["input_id"]
 *     (JsonApi.cpp:641-661).
 *   - the "unkown audio_action" error string is misspelled in production.
 * A sub-ticket that finds another one writes it in FINDINGS.md and pins it as
 * it is. Touching src/ during characterization destroys the reference.
 *
 * ---------------------------------------------------------------------------
 * OUT OF SCOPE
 * ---------------------------------------------------------------------------
 * get_camera_pic and get_cover spawn calaos_picture through
 * uvw::ProcessHandle: excluded from characterization (their JSON error paths
 * are not).
 *
 * ---------------------------------------------------------------------------
 * TYPICAL USE
 * ---------------------------------------------------------------------------
 *      class MyTest: public CalaosTest::JsonApiCharacterizationTest {};
 *
 *      TEST_F(MyTest, GetHome)
 *      {
 *          loadReferenceHouse();
 *
 *          WsTestSession ws;                    // already authenticated
 *          ws.send(Json{{ "msg", "get_home" }, { "msg_id", "1" }});
 *
 *          ASSERT_EQ(1u, ws.count());
 *          EXPECT_JSON_GOLDEN("ws_get_home", ws.lastMessage());
 *      }
 *
 *      TEST_F(MyTest, GetHomeHttp)
 *      {
 *          loadReferenceHouse();
 *
 *          HttpTestRequest req;                 // fresh client, one shot
 *          req.send(authenticated(Json{{ "action", "get_home" }}));
 *
 *          EXPECT_EQ("HTTP/1.0 200 OK", req.statusLine());
 *          EXPECT_JSON_GOLDEN("http_get_home", req.body());
 *      }
 *
 * Everything is a singleton in the server, so these tests must not be run in
 * parallel inside a single process (same caveat as CalaosCoreFixture).
 ******************************************************************************/

