class ClimateStatusTest: public JsonApiCharacterizationTest
{
protected:
    void SetUp() override
    {
        JsonApiCharacterizationTest::SetUp();
        for (const char *id: { "lk", "lk2", "lkc", "mo", "st", "nosensor", "dw", "px_mode" })
            forgetIOState(id);
        loadConfig(house(), rulesXmlDocument(""));
        loadedAt = std::chrono::steady_clock::now();
        //The first evaluation, on the first loop turn.
        pumpFor(20);
    }

    std::chrono::steady_clock::time_point loadedAt;

    static Device *dev(const std::string &id) { return ListeRoom::Instance().findIOAs<Device>(id); }
    static Json state(const std::string &id) { return dev(id)->deviceObject().at("state"); }

    static void set(const std::string &id, double v) { io(id)->set_value(v); }
    static void mode(const std::string &id, const std::string &m) { dev(id)->set_value(m); }

    //The last state published for `id`, once one satisfies `pred`.
    static bool publishedWhere(const WsTestSession &ws, const std::string &id,
                               const std::function<bool(const Json &)> &pred, int ms = 3000)
    {
        return pumpUntil([&]()
                         {
            const auto all = published(ws, id);
            return !all.empty() && pred(all.back());
        },
                         ms);
    }
};

//A wanted output held by its min_off_time: which one, and the seconds left.
TEST_F(ClimateStatusTest, ALockOutSaysWhichOutputAndHowLong)
{
    WsTestSession ws;
    EXPECT_FALSE(state("lk").contains("lockout"));

    set("lk_target", 21);
    set("lk_temp", 18);
    mode("lk", "heat");
    ASSERT_FALSE(io("lk_heat")->get_value_bool());

    const Json s = state("lk");
    ASSERT_TRUE(s.contains("lockout")) << s.dump();
    EXPECT_EQ(s.at("lockout").at("output"), "heat");
    ASSERT_TRUE(s.at("lockout").at("remaining").is_number_integer()) << s.dump();
    //Rounded up: min_off_time counts from the start, a moment ago.
    const double elapsed = std::chrono::duration<double>(std::chrono::steady_clock::now() - loadedAt).count();
    EXPECT_GE(s.at("lockout").at("remaining").get<int>(), 30 - elapsed);
    EXPECT_LE(s.at("lockout").at("remaining").get<int>(), 30);
    EXPECT_TRUE(publishedWhere(ws, "lk", [](const Json &st)
                               {
        return st.contains("lockout");
    }));

    //Nothing wanted any more: the lock-out goes, and that is published.
    mode("lk", "off");
    EXPECT_FALSE(state("lk").contains("lockout"));
    EXPECT_TRUE(publishedWhere(ws, "lk", [](const Json &st)
                               {
        return !st.contains("lockout");
    }));
}

TEST_F(ClimateStatusTest, ALockOutOfTheCoolingOutputSaysCool)
{
    WsTestSession ws;
    set("lkc_target", 21);
    set("lkc_temp", 25);
    mode("lkc", "cool");
    ASSERT_FALSE(io("lkc_cool")->get_value_bool());
    EXPECT_EQ(state("lkc").at("lockout").at("output"), "cool");
    EXPECT_TRUE(publishedWhere(ws, "lkc", [](const Json &st)
                               {
        return st.contains("lockout") && st.at("lockout").at("output") == "cool";
    }));
}

TEST_F(ClimateStatusTest, TheRemainingTimeIsComputedAtEachPublication)
{
    set("lk_target", 21);
    set("lk_temp", 18);
    mode("lk", "heat");
    const int first = state("lk").at("lockout").at("remaining").get<int>();
    pumpFor(1100);
    const int later = state("lk").at("lockout").at("remaining").get<int>();
    EXPECT_LT(later, first);
}

//The end of a lock-out is published without anything else changing.
TEST_F(ClimateStatusTest, TheEndOfALockOutIsPublished)
{
    WsTestSession ws;
    set("lk2_target", 21);
    set("lk2_temp", 18);
    mode("lk2", "heat");
    ASSERT_TRUE(state("lk2").contains("lockout"));

    ASSERT_TRUE(pumpUntil([]()
                          {
        return io("lk2_heat")->get_value_bool();
    }));
    EXPECT_FALSE(state("lk2").contains("lockout"));
    EXPECT_TRUE(publishedWhere(ws, "lk2", [](const Json &st)
                               {
        return !st.contains("lockout") && st.value("action", "") == "heating";
    }));
}

//A stale sensor holds the outputs off: said, and unsaid with the next reading.
TEST_F(ClimateStatusTest, AStaleSensorIsAFaultWhileItLasts)
{
    WsTestSession ws;
    set("st_target", 21);
    set("st_temp", 18);
    mode("st", "heat");
    EXPECT_FALSE(state("st").contains("fault"));

    ASSERT_TRUE(publishedWhere(ws, "st", [](const Json &st)
                               {
        return st.value("fault", "") == "sensor_stale";
    }));
    set("st_temp", 18);
    EXPECT_FALSE(state("st").contains("fault"));
    EXPECT_TRUE(publishedWhere(ws, "st", [](const Json &st)
                               {
        return !st.contains("fault");
    }));
}

//No sensor linked, or none read since the start: the sensor is missing.
//Mode off holds nothing: no fault.
TEST_F(ClimateStatusTest, AMissingSensorIsAFaultUnlessTheModeIsOff)
{
    set("nosensor_target", 21);
    EXPECT_FALSE(state("nosensor").contains("fault"));
    mode("nosensor", "heat");
    EXPECT_EQ(state("nosensor").value("fault", ""), "sensor_missing");

    set("dw_target", 21);
    mode("dw", "heat");
    EXPECT_EQ(state("dw").value("fault", ""), "sensor_missing");
    set("dw_temp", 18);
    EXPECT_FALSE(state("dw").contains("fault"));
    mode("dw", "off");
    io("dw_temp")->setStatusInfo(IOBase::StatusType::Connected,
                                 IOBase::StatusConnected::STATUS_DISCONNECTED);
    EXPECT_FALSE(state("dw").contains("fault"));
}

//Floor cooling: humidity at the maximum, or not read, holds output_cool off.
TEST_F(ClimateStatusTest, TheDewPointCutIsAFault)
{
    WsTestSession ws;
    set("dw_target", 21);
    set("dw_temp", 25);
    mode("dw", "cool");
    EXPECT_EQ(state("dw").value("fault", ""), "humidity_stale");
    EXPECT_FALSE(state("dw").contains("humidity"));

    set("dw_hum", 70);
    EXPECT_EQ(state("dw").value("fault", ""), "humidity_high");
    EXPECT_EQ(state("dw").at("humidity"), 70);
    EXPECT_TRUE(publishedWhere(ws, "dw", [](const Json &st)
                               {
        return st.value("fault", "") == "humidity_high";
    }));

    set("dw_hum", 50);
    EXPECT_FALSE(state("dw").contains("fault"));
    EXPECT_EQ(state("dw").at("humidity"), 50);
    EXPECT_TRUE(publishedWhere(ws, "dw", [](const Json &st)
                               {
        return !st.contains("fault");
    }));
}

//The thermostat's sensor, the proxy's mode IO: their availability.
TEST_F(ClimateStatusTest, ADisconnectedSensorOrApplianceIsPublished)
{
    WsTestSession ws;
    set("dw_temp", 20);
    EXPECT_FALSE(state("dw").contains("connected"));
    io("dw_temp")->setStatusInfo(IOBase::StatusType::Connected,
                                 IOBase::StatusConnected::STATUS_DISCONNECTED);
    EXPECT_EQ(state("dw").at("connected"), false);
    EXPECT_TRUE(publishedWhere(ws, "dw", [](const Json &st)
                               {
        return st.contains("connected");
    }));
    io("dw_temp")->setStatusInfo(IOBase::StatusType::Connected,
                                 IOBase::StatusConnected::STATUS_CONNECTED);
    EXPECT_FALSE(state("dw").contains("connected"));
    EXPECT_TRUE(publishedWhere(ws, "dw", [](const Json &st)
                               {
        return !st.contains("connected");
    }));

    EXPECT_FALSE(state("px").contains("connected"));
    io("px_mode")->setStatusInfo(IOBase::StatusType::Connected,
                                 IOBase::StatusConnected::STATUS_DISCONNECTED);
    EXPECT_EQ(state("px").at("connected"), false);
    EXPECT_TRUE(publishedWhere(ws, "px", [](const Json &st)
                               {
        return st.contains("connected");
    }));
}

