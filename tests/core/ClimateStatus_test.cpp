std::string link(const std::string &name, const std::string &io)
{
    return "      <calaos:link name=\"" + name + "\" io=\"" + io + "\" />\n";
}

std::string param(const std::string &name, const std::string &value)
{
    return "      <calaos:param name=\"" + name + "\" value=\"" + value + "\" />\n";
}

std::string internal(const std::string &type, const std::string &id)
{
    return "      <calaos:internal type=\"" + type + "\" id=\"" + id + "\" name=\"" + id +
           "\" visible=\"false\" />\n";
}

/* <id>: owned setpoints (none set), action and outputs, the sensor <id>_temp
 * in the room. `cool` adds an output_cool and a range. */
std::string thermostat(const std::string &id, bool cool, const std::string &params,
                       bool sensor = true)
{
    std::string inner = internal("InternalInt", id + "_target") +
                        internal("InternalString", id + "_action") +
                        internal("InternalBool", id + "_heat") + link("target_temp", id + "_target") +
                        link("action", id + "_action") + link("output_heat", id + "_heat");
    if (sensor)
        inner += link("current_temp", id + "_temp");
    if (cool)
        inner += internal("InternalInt", id + "_low") + internal("InternalInt", id + "_high") +
                 internal("InternalBool", id + "_cool") + link("target_temp_low", id + "_low") +
                 link("target_temp_high", id + "_high") + link("output_cool", id + "_cool");
    std::string room = "    <calaos:device id=\"" + id +
                       "\" type=\"climate\" impl=\"thermostat\" name=\"" + id + "\">\n" + inner +
                       params + "    </calaos:device>\n";
    if (sensor)
        room += internal("InternalInt", id + "_temp");
    return room;
}

std::string house()
{
    std::string ios;
    //A long lock-out, and one that ends during the case.
    ios += thermostat("lk", false, param("min_off_time", "30"));
    ios += thermostat("lk2", false, param("min_off_time", "0.3"));
    ios += thermostat("lkc", true, param("min_off_time", "3"));
    //A stop held by min_on_time is not a lock-out: nothing wanted waits.
    ios += thermostat("mo", false, param("min_on_time", "3"));
    ios += thermostat("st", false, param("sensor_timeout", "0.3"));
    ios += thermostat("nosensor", false, "", false);
    ios += thermostat("dw", true,
                      param("emitter", "floor") + link("humidity", "dw_hum") +
                          param("humidity_max", "65"));
    ios += internal("InternalInt", "dw_hum");
    //The factory key is case-insensitive.
    std::string upper = thermostat("uc", false, "");
    upper.replace(upper.find("impl=\"thermostat\""), 17, "impl=\"Thermostat\"");
    ios += upper;

    //An appliance reporting its humidity, its mode IO carrying its availability.
    ios += "    <calaos:device id=\"px\" type=\"climate\" impl=\"proxy\" name=\"px\">\n" +
           internal("InternalString", "px_mode") + internal("InternalInt", "px_hum") +
           "      <calaos:link name=\"mode\" io=\"px_mode\" command_io=\"px_mode\" />\n" +
           link("humidity", "px_hum") + "    </calaos:device>\n";
    return ioXmlDocument(roomXml("Salon", "salon", ios));
}

//The io_changed device states of `id` delivered to the session, in order.
std::vector<Json> published(const WsTestSession &ws, const std::string &id)
{
    std::vector<Json> res;
    for (const std::string &m: ws.messages())
    {
        const Json env = Json::parse(m, nullptr, false);
        if (!env.is_object() || env.value("msg", "") != "event")
            continue;
        const Json &ev = env.at("data");
        if (ev.value("type_str", "") == "io_changed" && ev.at("data").value("id", "") == id &&
            ev.at("data").contains("device"))
            res.push_back(ev.at("data").at("device").at("state"));
    }
    return res;
}

//Runs the real loop until `done` or the deadline.
bool pumpUntil(const std::function<bool()> &done, int ms = 3000)
{
    const auto end = std::chrono::steady_clock::now() + std::chrono::milliseconds(ms);
    while (std::chrono::steady_clock::now() < end)
    {
        pumpEventLoop(1);
        if (done())
            return true;
        std::this_thread::sleep_for(std::chrono::milliseconds(2));
    }
    return done();
}

void pumpFor(int ms)
{
    pumpUntil([]()
              {
        return false;
    },
              ms);
}

