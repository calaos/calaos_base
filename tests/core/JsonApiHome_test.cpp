/*******************************************************************************
 * The sixteen candidate keys of buildJsonIO(), and the seventeenth.
 *
 * ADDED AFTER A REVIEW COUNTER-MUTATION. The first version of this file claimed
 * its goldens "exhibited the absence contract" on eight keys. Six of them -
 * hits, chauffage_id, auto_scenario, step, io_style, value_warning - were in
 * fact absent because NO IO OF THE REFERENCE HOUSE SET THEM. Renaming four of
 * them in JsonApi.cpp:259-262 left all 52 cases green: the net saw nothing.
 * They are real production params (ListeRoom.cpp:276 reads chauffage_id,
 * IO/OutputAnalog.cpp:39 documents step, IO/InputSwitch.cpp:48 io_style,
 * IO/InputAnalog.cpp:66 value_warning).
 *
 * HOUSE_ACCENTED now sets every optional one, so the sixteen keys are pinned
 * BOTH by the goldens and by the explicit list below - a rename in production
 * cannot pass any more. The three cases are complementary on purpose: the
 * presence side, the absence side, and status_info which no configuration can
 * produce.
 ******************************************************************************/

TEST_F(JsonApiHomeTest, GetIoEmitsTheSixteenKeysForAFullyConfiguredIo)
{
    loadReferenceHouse();

    WsTestSession ws;
    ws.send(Json{{ "msg", "get_io" },
                 { "msg_id", "1" },
                 { "data", {{ "items", Json::array({ HOUSE_ACCENTED }) }} }});

    ASSERT_EQ(1u, ws.count());
    const Json jio = ws.lastData()[HOUSE_ACCENTED];
    ASSERT_TRUE(jio.is_object());

    //the exact list of JsonApi.cpp:258-262, in that order, spelled out so a
    //rename in production fails HERE with the key name in the message
    const std::vector<std::string> keys =
    { "id", "name", "type", "hits", "var_type", "visible",
      "chauffage_id", "rw", "unit", "gui_type", "state",
      "auto_scenario", "step", "io_type", "io_style",
      "value_warning" };

    for (const std::string &k: keys)
        EXPECT_TRUE(jio.contains(k)) << "buildJsonIO() no longer emits " << k;

    //status_info is the only other key it can add, and this IO has none
    EXPECT_EQ(keys.size(), jio.size()) << jio.dump();

    //the seven configured through XML, with their values, all as strings
    EXPECT_EQ("12", jio.value("hits", std::string()));
    EXPECT_EQ("e40_heater", jio.value("chauffage_id", std::string()));
    EXPECT_EQ("\xc2\xb0""C", jio.value("unit", std::string()));
    EXPECT_EQ("e40_scenario", jio.value("auto_scenario", std::string()));
    EXPECT_EQ("0.5", jio.value("step", std::string()));
    EXPECT_EQ("temperature", jio.value("io_style", std::string()));
    EXPECT_EQ("false", jio.value("value_warning", std::string()));
}

