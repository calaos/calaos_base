/*******************************************************************************
 * E4.0b - the model and the state: the nine commands every client of the JSON
 * API calls, on BOTH transports.
 *
 *      get_home  get_io  get_state  get_states  query
 *      get_param  set_param  del_param  set_state
 *
 * This file freezes what the code does TODAY. It fixes nothing and improves
 * nothing: several cases below pin behaviour that is unambiguously wrong (see
 * "FROZEN BUGS" further down). Correcting a behaviour while characterizing it
 * destroys the reference the E4.1 migration will be judged against.
 *
 * Everything goes through the E4.0a harness (tests/core/JsonApiCharacterization.h,
 * read it before touching anything here): semantic oracle, one golden per case,
 * goldens GENERATED by CALAOS_GOLDEN_UPDATE=1 and never hand written.
 *
 * ---------------------------------------------------------------------------
 * WHAT THE TWO TRANSPORTS DO NOT AGREE ON - characterized here, not fixed
 * ---------------------------------------------------------------------------
 *  - get_io / get_state read their "items" array from DIFFERENT PLACES:
 *    WS reads jsonRoot["data"]["items"] (JsonApiHandlerWS.cpp:255, :314), HTTP
 *    reads the ROOT object's "items" (JsonApiHandlerHttp.cpp:285, :349). The
 *    exact same document sent to both transports does not address the same IOs.
 *  - HTTP additionally accepts "items" as a COMMA SEPARATED STRING through the
 *    GET parameter fallback (JsonApiHandlerHttp.cpp:300-303, :364-367). WS has
 *    no equivalent.
 *  - set_state over WS answers NOTHING when the request carries no msg_id
 *    (JsonApiHandlerWS.cpp:334) while HTTP always answers. A fire-and-forget
 *    set_state is silent by design over WS; over HTTP it is not.
 *  - set_param / del_param are refused for a service-scoped session over WS
 *    (scope denied); the HTTP transport has no scope notion at all.
 *
 * ---------------------------------------------------------------------------
 * FROZEN BUGS - pinned on purpose, DO NOT FIX HERE
 * ---------------------------------------------------------------------------
 *  - buildQuery() (JsonApi.cpp:641-661) gates on jParam.Exists("id") but looks
 *    the IO up with jParam["input_id"]. A well formed {"id": <valid io>} query
 *    therefore answers {"error":"wrong id"}, and a query carrying only
 *    "input_id" answers {} without ever looking anything up. Both pinned.
 *  - get_param on a KNOWN io and an UNKNOWN param is not an error: it answers
 *    {"<param>":""}, an empty string (JsonApi.cpp:672, get_param() on a missing
 *    key returns ""). "wrong io/param" is reserved for an unknown IO.
 *  - get_param with no "param" member at all answers {"":""} - a JSON object
 *    with an EMPTY KEY. Same root cause.
 *  - get_states/query are effectively dead for every IO of the tree except
 *    IOAVReceiver: get_all_values_*() and query_param() are only overridden
 *    there (IOBase.h:103-111), so every other IO answers {}. Measured, and
 *    reported as a finding, not fixed.
 ******************************************************************************/

#include "JsonApiCharacterization.h"

