class JsonApiHomeTest: public JsonApiCharacterizationTest
{
protected:
    //The four IOs of the first room plus the accented one of the second: every
    //IO of the reference house that is neither a camera nor a player, i.e.
    //everything get_state can answer synchronously.
    static Json plainItems()
    {
        return Json::array({ HOUSE_BOOL_IN, HOUSE_BOOL_OUT, HOUSE_INT,
                             HOUSE_STRING, HOUSE_ACCENTED });
    }

    //Same list plus the two cameras. Deliberately excludes the player: a player
    //makes buildJsonState() asynchronous, which is characterized on its own
    //below.
    static Json plainAndCameraItems()
    {
        Json j = plainItems();
        j.push_back(HOUSE_CAMERA_PTZ);
        j.push_back(HOUSE_CAMERA_PLAIN);
        return j;
    }

    //Walks a whole document and fails on the first JSON null it finds. The
    //"absent key, never null" contract of buildJsonIO() (JsonApi.cpp:286
    //`continue`) is the single most fragile thing of the migration: a
    //`j[key] = nullptr` written by reflex would create the key instead of
    //skipping it, and every golden here would still pass on the keys it does
    //list.
    static ::testing::AssertionResult hasNoNullAnywhere(const Json &j,
                                                        const std::string &path = "")
    {
        if (j.is_null())
            return ::testing::AssertionFailure() << "null at " << (path.empty()? "/": path);

        if (j.is_object())
        {
            for (auto it = j.begin(); it != j.end(); ++it)
            {
                auto res = hasNoNullAnywhere(it.value(), path + "/" + it.key());
                if (!res) return res;
            }
        }
        else if (j.is_array())
        {
            for (size_t i = 0; i < j.size(); i++)
            {
                auto res = hasNoNullAnywhere(j[i], path + "/" + std::to_string(i));
                if (!res) return res;
            }
        }

        return ::testing::AssertionSuccess();
    }

    //Every leaf of the document must be a JSON string. The whole API is
    //stringified today (JsonApi.cpp holds 32 json_string and zero json_integer
    /// json_real / json_true); buildJsonEventLog() is the single exception and
    //it belongs to E4.0e, not here.
    static ::testing::AssertionResult everyLeafIsAString(const Json &j,
                                                          const std::string &path = "")
    {
        if (j.is_object())
        {
            for (auto it = j.begin(); it != j.end(); ++it)
            {
                auto res = everyLeafIsAString(it.value(), path + "/" + it.key());
                if (!res) return res;
            }
            return ::testing::AssertionSuccess();
        }

        if (j.is_array())
        {
            for (size_t i = 0; i < j.size(); i++)
            {
                auto res = everyLeafIsAString(j[i], path + "/" + std::to_string(i));
                if (!res) return res;
            }
            return ::testing::AssertionSuccess();
        }

        if (j.is_string())
            return ::testing::AssertionSuccess();

        return ::testing::AssertionFailure()
                << "non string leaf at " << path << ": " << j.dump();
    }
};

