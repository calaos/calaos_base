TEST_F(DeviceApiTest, ValidationHelpers)
{
    double d = -1;
    std::string reason;

    EXPECT_TRUE(TestClimate::numberField(Json(21.37), 16, 30, 0, d, reason));
    EXPECT_DOUBLE_EQ(d, 21.37);
    EXPECT_TRUE(TestClimate::numberField(Json(7), 16, 30, 1, d, reason));
    EXPECT_DOUBLE_EQ(d, 16);
    EXPECT_FALSE(TestClimate::numberField(Json("21"), 16, 30, 1, d, reason));
    EXPECT_EQ(reason, "not a JSON number");
    EXPECT_FALSE(TestClimate::numberField(Json(true), 16, 30, 1, d, reason));

    //No binary residue: 213 * 0.1 is 21.300000000000001.
    EXPECT_TRUE(TestClimate::numberField(Json(21.3), 0, 100, 0.1, d, reason));
    EXPECT_EQ(Json(d).dump(), "21.3");
    EXPECT_TRUE(TestClimate::numberField(Json(21.237), 0, 100, 0.01, d, reason));
    EXPECT_EQ(Json(d).dump(), "21.24");

    std::string s;
    EXPECT_TRUE(TestClimate::enumField(Json("heat"), { "off", "heat" }, s, reason));
    EXPECT_EQ(s, "heat");
    EXPECT_FALSE(TestClimate::enumField(Json("Heat"), { "off", "heat" }, s, reason));
    EXPECT_EQ(reason, "not one of: off heat");
    EXPECT_FALSE(TestClimate::enumField(Json::array({ "heat" }), { "off", "heat" }, s, reason));
}

