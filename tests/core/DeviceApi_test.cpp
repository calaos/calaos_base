std::string linkXml(const std::string &name, const std::string &io,
                    const std::string &commandIo = std::string())
{
    std::string x = "      <calaos:link name=\"" + name + "\" io=\"" + io + "\"";
    if (!commandIo.empty())
        x += " command_io=\"" + commandIo + "\"";
    return x + " />\n";
}

std::string deviceXml(const std::string &id, const std::string &impl, const std::string &inner)
{
    return "    <calaos:device id=\"" + id + "\" type=\"climate\" impl=\"" + impl +
           "\" name=\"" + id + "\">\n" + inner + "    </calaos:device>\n";
}

std::string ownedXml(const std::string &type, const std::string &id,
                     const std::string &extra = std::string())
{
    return "      <calaos:internal type=\"" + type + "\" id=\"" + id + "\" name=\"" + id +
           "\" visible=\"false\"" + extra + " />\n";
}

/* "clim": mode, target and an external sensor in a later room. "clim2": mode
 * only, so target_temp is not one of its fields. "bare": the base class, with
 * one resolved and one dangling link. */
std::string deviceHouse(const std::string &modeExtra = std::string())
{
    std::string clim = ownedXml("InternalString", DEV_MODE, modeExtra) +
                       ownedXml("InternalInt", DEV_TARGET) + ownedXml("InternalInt", DEV_LOW) +
                       ownedXml("InternalInt", DEV_HIGH) + ownedXml("InternalString", DEV_FAN) +
                       linkXml("mode", DEV_MODE, DEV_MODE) + linkXml("target_temp", DEV_TARGET) +
                       linkXml("target_temp_low", DEV_LOW) + linkXml("target_temp_high", DEV_HIGH) +
                       linkXml("fan_mode", DEV_FAN) + linkXml("current_temp", EXT_TEMP);
    //Mode without a command IO: commands write the mode IO itself.
    std::string clim2 = ownedXml("InternalString", DEV_NO_TARGET_MODE) +
                        linkXml("mode", DEV_NO_TARGET_MODE);
    std::string bare = linkXml("current_temp", EXT_TEMP) + linkXml("humidity", "nowhere");

    std::string salon;
    salon += internalIoXml("InternalBool", CoreFixture::ID_BOOL_OUT, "Bool output");
    salon += deviceXml(DEV, "test_climate", clim);
    salon += deviceXml(DEV_NO_TARGET, "test_climate", clim2);
    salon += deviceXml(DEV_BARE, "test_bare", bare);

    return ioXmlDocument(roomXml("Salon", "salon", salon) +
                         roomXml("Kitchen", "kitchen", internalIoXml("InternalInt", EXT_TEMP, "Temp")));
}

//The io_changed data of `id` delivered to the session, in order.
std::vector<Json> ioChanged(const WsTestSession &ws, const std::string &id)
{
    std::vector<Json> res;
    for (const std::string &m: ws.messages())
    {
        const Json env = Json::parse(m, nullptr, false);
        if (!env.is_object() || env.value("msg", "") != "event")
            continue;
        const Json &ev = env.at("data");
        if (ev.value("type_str", "") == "io_changed" && ev.at("data").value("id", "") == id)
            res.push_back(ev);
    }
    return res;
}

//Runs the real loop until `done` or the deadline, whichever comes first.
void pumpFor(int ms, const std::function<bool()> &done = nullptr)
{
    const auto end = std::chrono::steady_clock::now() + std::chrono::milliseconds(ms);
    while (std::chrono::steady_clock::now() < end)
    {
        pumpEventLoop(1);
        if (done && done())
            return;
        std::this_thread::sleep_for(std::chrono::milliseconds(2));
    }
}

