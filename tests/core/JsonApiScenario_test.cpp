class JsonApiScenarioTest: public JsonApiCharacterizationTest
{
protected:
    /* A small house of our own instead of loadReferenceHouse().
     * Two measured reasons, not taste:
     *  - the T3.18 cases save the WHOLE configuration to disk, amputate one IO
     *    from io.xml and load it back. Dragging two cameras and a Roon player
     *    through that cycle buys nothing and adds two failure modes;
     *  - the reference house carries no InPlageHoraire and no Scenario at all,
     *    which are the only two IO types this file is about.
     * The reference house is NOT modified: E4.0b's counter-mutation showed how
     * much its deliberate sparseness is worth, and this file has no need to
     * touch it.
     */
    void loadScenarioHouse()
    {
        loadConfig(ioXmlDocument(roomXml(E40C_ROOM_NAME, E40C_ROOM_TYPE, houseIosXml(), 0)),
                   rulesXmlDocument(std::string()));

        //Loading raises one EventIOAdded per IO. They sit in the EventManager
        //queue until something pumps the loop and are then delivered to every
        //live session, so a case pinning the ABSENCE of a message would trip
        //over them. Drain here, exactly like loadReferenceHouse() does.
        pumpEventLoop();
    }

    /* THE ONE PLACE that enumerates the keys of a Scenario::toJson() payload
     * (IO/Scenario.cpp:88-95, :146). T3.18 adds "broken",
     * "disabled_missing_io" and "missing_ios" HERE and nowhere else: every
     * structural assertion of this file reads this list.
     */
    static std::vector<std::string> scenarioPayloadKeys()
    {
        return { "id", "cycle", "enabled", "schedule", "category",
                 //T3.18, the three keys. "broken" is live (Rule::isDisabled()
                 //over the rules of the scenario), "disabled_missing_io" is the
                 //persisted sticky flag, and they DIVERGE on purpose.
                 "broken", "disabled_missing_io", "missing_ios",
                 "steps_count", "steps" };
    }

    /* The eleven keys of TimeRange::toParams() (src/lib/TimeRange.cpp:425-443),
     * same role for the time range payload.
     */
    static std::vector<std::string> timeRangePayloadKeys()
    {
        return { "day",
                 "start_hour", "start_min", "start_sec", "start_type", "start_offset",
                 "end_hour", "end_min", "end_sec", "end_type", "end_offset" };
    }

    //Every leaf of the document must be a JSON string: the whole API is
    //stringified today (32 json_string and zero json_integer in JsonApi.cpp).
    static ::testing::AssertionResult everyLeafIsAString(const Json &j,
                                                        const std::string &path = "")
    {
        if (j.is_object())
        {
            for (auto it = j.begin(); it != j.end(); ++it)
            {
                auto res = everyLeafIsAString(it.value(), path + "/" + it.key());
                if (!res) return res;
            }
            return ::testing::AssertionSuccess();
        }

        if (j.is_array())
        {
            for (size_t i = 0; i < j.size(); i++)
            {
                auto res = everyLeafIsAString(j[i], path + "/" + std::to_string(i));
                if (!res) return res;
            }
            return ::testing::AssertionSuccess();
        }

        if (j.is_string())
            return ::testing::AssertionSuccess();

        return ::testing::AssertionFailure()
                << "non string leaf at " << path << ": " << j.dump();
    }

    //Walks a document and answers true when `needle` appears as a whole string
    //value anywhere in it. Structural on purpose: searching a serialized dump
    //for a substring would be a comparison on serialized JSON, which this
    //series forbids, and it would also match a longer id containing this one.
    static bool mentionsValue(const Json &j, const std::string &needle)
    {
        if (j.is_string())
            return j.get<std::string>() == needle;

        if (j.is_object())
        {
            for (auto it = j.begin(); it != j.end(); ++it)
            {
                if (it.key() == needle) return true;
                if (mentionsValue(it.value(), needle)) return true;
            }
        }
        else if (j.is_array())
        {
            for (const Json &item: j)
                if (mentionsValue(item, needle)) return true;
        }

        return false;
    }

    //The type_str of every "event" message a session received, in order.
    static std::vector<std::string> eventTypes(const WsTestSession &ws)
    {
        std::vector<std::string> types;
        for (const std::string &m: ws.messages())
        {
            const Json env = Json::parse(m, nullptr, false);
            if (env.is_discarded() || env.value("msg", std::string()) != "event")
                continue;
            types.push_back(env["data"].value("type_str", std::string()));
        }
        return types;
    }

    static bool sawEvent(const std::vector<std::string> &types, const std::string &type)
    {
        return std::find(types.begin(), types.end(), type) != types.end();
    }

    /* ---------------------------------------------------------------------
     * Request shorthands. WS puts the sub-command under "data", HTTP puts it
     * at the root: keeping that asymmetry in one place is what makes the
     * divergence cases below readable.
     * ------------------------------------------------------------------ */

    static Json wsRequest(const std::string &msg, Json data,
                          const std::string &msgId = "e40c")
    {
        return Json{{ "msg", msg }, { "msg_id", msgId }, { "data", data }};
    }

    //Sends an autoscenario sub-command over WS and answers the "data" member
    //of the (single) reply. Fails the calling test when the reply count is not
    //exactly one.
    Json wsAutoscenario(WsTestSession &ws, Json data)
    {
        ws.clear();
        ws.send(wsRequest("autoscenario", data));
        EXPECT_EQ(1u, ws.count()) << "autoscenario " << data.value("type", std::string())
                                  << " answered " << ws.count() << " messages";
        if (ws.count() != 1) return Json::object();
        return ws.lastData();
    }

    /* The scenario every non-T3.18 case works on: two standard steps and a
     * synthetic end step, three different action targets, a non zero pause.
     * Answers the id of the Scenario IO, "io_0" on a fresh house.
     */
    std::string createReferenceScenario(WsTestSession &ws)
    {
        const Json ret = wsAutoscenario(ws, Json{
            { "type", "create" },
            { "name", "Soir\xc3\xa9""e" },   //accented on purpose, see E4.0a
            { "room_name", E40C_ROOM_NAME },
            { "room_type", E40C_ROOM_TYPE },
            { "steps", Json::array({
                Json{{ "step_type", "standard" }, { "step_pause", "1.5" },
                     { "actions", Json::array({ Json{{ "id", IO_BOOL }, { "action", "true" }} }) }},
                Json{{ "step_type", "standard" }, { "step_pause", "0" },
                     { "actions", Json::array({ Json{{ "id", IO_TARGET }, { "action", "true" }},
                                                Json{{ "id", IO_INT }, { "action", "42" }} }) }},
                Json{{ "step_type", "end" },
                     { "actions", Json::array({ Json{{ "id", IO_STRING }, { "action", "done" }} }) }}
            }) }});

        return ret.value("id", std::string());
    }

    static Scenario *scenarioIo(const std::string &id)
    {
        return dynamic_cast<Scenario *>(ListeRoom::Instance().get_io(id));
    }

    /* Amputate one IO element from an io.xml document, the way an installer
     * deleting a line from the file does. Self-closing elements only, which is
     * what every internal IO is written as.
     */
    static bool removeIoFromXml(std::string &xml, const std::string &id)
    {
        const size_t at = xml.find("id=\"" + id + "\"");
        if (at == std::string::npos) return false;
        const size_t start = xml.rfind('<', at);
        const size_t end = xml.find('>', at);
        if (start == std::string::npos || end == std::string::npos) return false;
        xml.erase(start, end - start + 1);
        return true;
    }

    /* Builds the reference scenario, then makes IO_TARGET vanish from io.xml
     * and reloads everything - the "someone deleted an IO from the config"
     * path. It is the ONLY path that leaves a step rule holding an id that
     * does not resolve: the hot path destroys the rule instead (see
     * DeletingAnIoUsedByAStepDestroysTheWholeStepRule).
     * On return the scenario is loaded, checkAutoScenario() has run, and the
     * step rule of step 2 is disabled with IO_TARGET as its missing id.
     */
    std::string loadScenarioWithAnAmputatedStep()
    {
        loadScenarioHouse();

        std::string scenarioId;
        {
            WsTestSession ws;
            scenarioId = createReferenceScenario(ws);
        }
        EXPECT_EQ(SCENARIO_IO_ID, scenarioId);

        saveConfig();

        std::string ioXml = ioXmlOnDisk();
        const std::string rulesXml = rulesXmlOnDisk();
        EXPECT_TRUE(removeIoFromXml(ioXml, IO_TARGET))
                << "the target IO was not found in the saved io.xml";
        EXPECT_EQ(std::string::npos, ioXml.find(IO_TARGET));
        //the rules keep the dead reference verbatim (ActionStd::SaveToXml(),
        //E4.2e): that is what makes this whole case possible
        EXPECT_NE(std::string::npos, rulesXml.find(IO_TARGET));

        clearCoreState();
        loadConfig(ioXml, rulesXml);
        ListeRoom::Instance().checkAutoScenario();
        pumpEventLoop();

        return scenarioId;
    }
};

