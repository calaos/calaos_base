/*******************************************************************************
 * >>> THE T3.18 BLOCK <<<
 *
 * Everything below characterizes what the API says about a scenario whose step
 * lost its IO. It says NOTHING today, which is the defect T3.18 corrects, and
 * that silence has never been recorded anywhere before this file.
 *
 * Two configurations are built, both from a REAL amputated configuration and
 * never by hand:
 *   - broken:  the IO is gone from io.xml, the step rule survives holding a
 *              dead reference (E4.2e keeps it verbatim), Rule::isDisabled() is
 *              true, and the payload shows an EMPTY STEP with no indication;
 *   - repaired: the same configuration with the IO put back. The reference
 *              resolves again, the payload is byte for byte the healthy one -
 *              while the rule is STILL disabled and the scenario still does
 *              nothing, because missingIoIds is only ever rebuilt at load.
 *
 * They are the two unhealthy goldens T3.18.md asks for. After T3.18 they carry
 * broken/disabled_missing_io as true/true and false/true respectively.
 ******************************************************************************/

TEST_F(JsonApiScenarioTest, ABrokenStepSilentlyLosesItsActionFromThePayload)
{
    //T3.18.md constat (d), measured here rather than argued: countRealActions()
    //skips the action because isScenarioInternalIO(nullptr) answers TRUE
    //(AutoScenario.cpp:706), so the step is answered with an empty "actions"
    //array - the exact shape of a step the user deliberately left empty.
    const std::string scenarioId = loadScenarioWithAnAmputatedStep();
    ASSERT_FALSE(scenarioId.empty());

    //the reference really is dead, and the rule really is disabled
    ASSERT_TRUE(io(IO_TARGET) == nullptr);
    Scenario *sc = scenarioIo(scenarioId);
    ASSERT_TRUE(sc != nullptr && sc->getAutoScenario() != nullptr);
    const std::vector<Rule *> steps = sc->getAutoScenario()->getRuleSteps();
    ASSERT_EQ(2u, steps.size()) << "the load path KEEPS the step rule";
    ASSERT_TRUE(steps[1] != nullptr);
    EXPECT_TRUE(steps[1]->isDisabled()) << "E4.2e should have disabled the step rule";

    WsTestSession ws;
    ws.send(wsRequest("autoscenario", Json{{ "type", "get" }, { "id", scenarioId }},
                      "e40c-broken"));
    ASSERT_EQ(1u, ws.count());
    EXPECT_JSON_GOLDEN("e40c_ws_autoscenario_get_broken", ws.lastMessage());

    const Json payload = ws.lastData();
    //the payload says the scenario has two steps and that one of them does
    //nothing. It does not say WHY, and it does not say the scenario is dead.
    EXPECT_EQ("2", payload.value("steps_count", std::string()));
    ASSERT_EQ(3u, payload["steps"].size());
    EXPECT_EQ(1u, payload["steps"][1]["actions"].size())
            << "only the surviving action of step 2 is left: " << payload["steps"][1].dump();
    EXPECT_EQ(IO_INT, payload["steps"][1]["actions"][0].value("id", std::string()));
    //not one key of the payload mentions the loss - THIS is what T3.18 changes
    for (const std::string &k: scenarioPayloadKeys())
        EXPECT_TRUE(payload.contains(k));
    EXPECT_EQ(scenarioPayloadKeys().size(), payload.size()) << payload.dump();
    /* T3.18 - EXPECTED VALUE FLIPPED. This used to be EXPECT_FALSE: the dead id
     * was nowhere in the payload, which is the silence the ticket removes. It
     * is now carried by "missing_ios", and the step is still rendered without
     * its action - the payload does not gain the action back, it gains the
     * DIAGNOSIS.
     */
    EXPECT_TRUE(mentionsValue(payload, IO_TARGET))
            << "missing_ios does not name the dead id: " << payload.dump();
    EXPECT_EQ(IO_TARGET, payload.value("missing_ios", std::string()));
    EXPECT_EQ("true", payload.value("broken", std::string()));
    EXPECT_EQ("true", payload.value("disabled_missing_io", std::string()));
}

