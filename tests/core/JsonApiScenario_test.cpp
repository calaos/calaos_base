    ASSERT_EQ(1u, ws.count());
    EXPECT_JSON_GOLDEN("e40c_ws_autoscenario_get_repaired", ws.lastMessage());

    const Json repaired = ws.lastData();

    //live state: nothing is missing any more, on any rule of the scenario
    Scenario *sc = scenarioIo(scenarioId);
    ASSERT_TRUE(sc != nullptr && sc->getAutoScenario() != nullptr);
    const std::vector<Rule *> steps = sc->getAutoScenario()->getRuleSteps();
    ASSERT_EQ(2u, steps.size());
    ASSERT_TRUE(steps[1] != nullptr);
    EXPECT_FALSE(steps[1]->isDisabled())
            << "the reload should have cleared the missing io of the step rule";

