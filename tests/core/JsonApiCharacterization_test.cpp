/*******************************************************************************
 * The oracle itself. Executable specification of the comparison contract: if
 * one of these ever fails, every golden in the series became meaningless.
 ******************************************************************************/

TEST_F(JsonApiCharacterizationTestSuite, OracleIsBlindToKeyOrder)
{
    //jansson emits insertion order, nlohmann emits sorted keys, and the user
    //has already accepted the change. The tree even emits the WS envelope in
    //two different orders today depending on the sendJson() overload.
    EXPECT_JSON_EQ(std::string(R"({"msg":"get_home","msg_id":"1","data":{"a":"b"}})"),
                   std::string(R"({"data":{"a":"b"},"msg_id":"1","msg":"get_home"})"));
}

TEST_F(JsonApiCharacterizationTestSuite, OracleIsStrictOnTypes)
{
    //"3" is not 3. The whole API is stringified today; a migration that
    //"improves" a stringified number into a JSON number must break the net.
    const Json stringy = Json::parse(R"({"type":"3"})");
    const Json numeric = Json::parse(R"({"type":3})");

    EXPECT_NE(stringy, numeric);
    EXPECT_FALSE(firstJsonDifference(stringy, numeric).empty());
    EXPECT_NE(std::string::npos, firstJsonDifference(stringy, numeric).find("/type"));
}

TEST_F(JsonApiCharacterizationTestSuite, OracleKeepsArrayOrderSignificant)
{
    //Room, IO and rule order drives evaluation order (invariant of the E4.2
    //series). Never sort an array before comparing.
    const Json a = Json::parse(R"({"home":[{"name":"A"},{"name":"B"}]})");
    const Json b = Json::parse(R"({"home":[{"name":"B"},{"name":"A"}]})");

    EXPECT_FALSE(firstJsonDifference(a, b).empty());
    EXPECT_NE(std::string::npos, firstJsonDifference(a, b).find("/home/0/name"));
}

TEST_F(JsonApiCharacterizationTestSuite, OracleReportsThePathOfTheFirstDivergence)
{
    //A raw EXPECT_EQ on a 200 key object is unusable during a migration. The
    //assertion has to say WHERE.
    const Json expected = Json::parse(
        R"({"home":[{"items":[{"id":"a","state":"true"},{"id":"b","state":"false"}]}]})");
    const Json actual = Json::parse(
        R"({"home":[{"items":[{"id":"a","state":"true"},{"id":"b","state":"true"}]}]})");

    const std::string diff = firstJsonDifference(expected, actual);
    EXPECT_NE(std::string::npos, diff.find("/home/0/items/1/state")) << diff;
}

TEST_F(JsonApiCharacterizationTestSuite, OracleReportsAMissingAndAnExtraKey)
{
    const Json expected = Json::parse(R"({"a":"1","b":"2"})");
    const Json missing = Json::parse(R"({"a":"1"})");
    const Json extra = Json::parse(R"({"a":"1","b":"2","c":"3"})");

    EXPECT_NE(std::string::npos, firstJsonDifference(expected, missing).find("/b"));
    EXPECT_NE(std::string::npos, firstJsonDifference(expected, extra).find("/c"));
}

/*******************************************************************************
 * NEGATIVE tests of the assertions themselves.
 *
 * The five cases above exercise firstJsonDifference() directly. That is NOT
 * enough: what the five sub-tickets will actually write is EXPECT_JSON_EQ and
 * EXPECT_JSON_GOLDEN, and a misplaced AssertionSuccess() in either wrapper
 * would leave the whole series green forever - including a mutation run, which
 * would only be caught if it happened to go through the other wrapper.
 *
 * So every macro this harness exports is proven here to FAIL, on the right
 * input, with the right message. EXPECT_NONFATAL_FAILURE swallows the failure
 * and asserts that exactly one occurred and that its text contains the given
 * substring.
 *
 * gtest constraint: the statement inside EXPECT_NONFATAL_FAILURE must not
 * reference local non-static variables, hence the literals everywhere.
 ******************************************************************************/

TEST_F(JsonApiCharacterizationTestSuite, NegativeExpectJsonEqFailsOnADifferentValue)
{
    EXPECT_NONFATAL_FAILURE(
        EXPECT_JSON_EQ(std::string(R"({"a":"1"})"), std::string(R"({"a":"2"})")),
        "/a");
}

TEST_F(JsonApiCharacterizationTestSuite, NegativeExpectJsonEqFailsOnAStringVersusANumber)
{
    //The single most valuable negative: if this ever stops failing, the whole
    //"everything is stringified" contract stops being pinned.
    EXPECT_NONFATAL_FAILURE(
        EXPECT_JSON_EQ(std::string(R"({"type":"3"})"), std::string(R"({"type":3})")),
        "/type");
}

TEST_F(JsonApiCharacterizationTestSuite, NegativeExpectJsonEqFailsOnArrayOrder)
{
    EXPECT_NONFATAL_FAILURE(
        EXPECT_JSON_EQ(std::string(R"({"h":[{"n":"A"},{"n":"B"}]})"),
                       std::string(R"({"h":[{"n":"B"},{"n":"A"}]})")),
        "/h/0/n");
}

