/*******************************************************************************
 * Events. E4.0d owns the campaign; what is proven here is the pump, which
 * settles point (c) of E4.0.md.
 ******************************************************************************/

TEST_F(JsonApiCharacterizationTestSuite, EventsAreOnlyDeliveredOnceTheLoopIsPumped)
{
    loadReferenceHouse();

    WsTestSession ws;

    Params p;
    p.Add("state", "true");
    EventManager::create(CalaosEvent::EventIOChanged, HOUSE_BOOL_IN, p,
                         false /*logHistory*/);

    //EventManager queues into a uvw Idler. Without a loop iteration the queue
    //simply grows and nothing is ever delivered - exactly what
    //CalaosCoreFixture.h warns about.
    ASSERT_EQ(0u, ws.count());

    pumpEventLoop();

    ASSERT_EQ(1u, ws.count());
    const Json env = ws.lastEnvelope();
    EXPECT_EQ("event", env.value("msg", std::string()));
    //push events are unsolicited: no msg_id
    EXPECT_FALSE(env.contains("msg_id"));
    ASSERT_TRUE(env.contains("data"));
    EXPECT_EQ("io_changed", env["data"].value("type_str", std::string()));
    //every value is a string, the enum is stringified
    EXPECT_TRUE(env["data"]["type"].is_string());
    EXPECT_EQ(HOUSE_BOOL_IN, env["data"]["data"].value("id", std::string()));
}

