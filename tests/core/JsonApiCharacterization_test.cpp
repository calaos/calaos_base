TEST_F(JsonApiCharacterizationTestSuite, HttpAndWsAgreeOnTheGetHomePayload)
{
    //The HTTP body is, by construction, the dump of the same object the WS
    //envelope carries under "data". Pinning that equality is what lets the
    //other sub-tickets characterize a payload once instead of twice.
    loadReferenceHouse();

    WsTestSession ws;
    ws.send(Json{{ "msg", "get_home" }, { "msg_id", "1" }});
    ASSERT_EQ(1u, ws.count());

    HttpTestRequest req;
    req.send(authenticated(Json{{ "action", "get_home" }}));
    ASSERT_EQ(1u, req.count());

    EXPECT_JSON_EQ(ws.lastData(), req.bodyJson());
}

