TEST_F(JsonApiCharacterizationTestSuite, WsGetHomeEnvelopeCarriesTheMsgId)
{
    loadReferenceHouse();

    WsTestSession ws;
    ws.send(Json{{ "msg", "get_home" }, { "msg_id", "42" }});

    ASSERT_EQ(1u, ws.count());
    const Json env = ws.lastEnvelope();
    ASSERT_TRUE(env.is_object());
    EXPECT_EQ("get_home", env.value("msg", std::string()));
    EXPECT_EQ("42", env.value("msg_id", std::string()));
    ASSERT_TRUE(env.contains("data"));
    //get_home answers three top level members, always present, even empty.
    EXPECT_TRUE(env["data"].contains("home"));
    EXPECT_TRUE(env["data"].contains("cameras"));
    EXPECT_TRUE(env["data"].contains("audio"));
}

TEST_F(JsonApiCharacterizationTestSuite, WsGetHomeKeepsRoomAndIoOrder)
{
    loadReferenceHouse();

    WsTestSession ws;
    ws.send(Json{{ "msg", "get_home" }, { "msg_id", "1" }});

    ASSERT_EQ(1u, ws.count());
    const Json home = ws.lastEnvelope()["data"]["home"];
    ASSERT_TRUE(home.is_array());
    ASSERT_EQ(2u, home.size());
    EXPECT_EQ(HOUSE_ROOM1_NAME, home[0].value("name", std::string()));
    EXPECT_EQ(HOUSE_ROOM2_NAME, home[1].value("name", std::string()));

    const Json items = home[0]["items"];
    ASSERT_EQ(4u, items.size());
    EXPECT_EQ(HOUSE_BOOL_IN, items[0].value("id", std::string()));
    EXPECT_EQ(HOUSE_BOOL_OUT, items[1].value("id", std::string()));
    EXPECT_EQ(HOUSE_INT, items[2].value("id", std::string()));
    EXPECT_EQ(HOUSE_STRING, items[3].value("id", std::string()));
}

TEST_F(JsonApiCharacterizationTestSuite, NonAsciiSurvivesTheEscapingDifference)
{
    //jansson dumps with JSON_ENSURE_ASCII, so the wire carries É escapes;
    //nlohmann writes raw UTF-8. Parsing dissolves the difference, which is why
    //the oracle can be semantic. This is the case that proves it.
    loadReferenceHouse();

    WsTestSession ws;
    ws.send(Json{{ "msg", "get_home" }, { "msg_id", "1" }});

    ASSERT_EQ(1u, ws.count());

    //the raw wire really does carry the escape, not the UTF-8 bytes (jansson
    //writes the hex digits in upper case, hence the normalisation)
    std::string wire = ws.lastMessage();
    for (char &c: wire)
        c = (char)::tolower((unsigned char)c);
    EXPECT_NE(std::string::npos, wire.find("\\u00c9"));
    EXPECT_EQ(std::string::npos, ws.lastMessage().find("\xc3\x89"));

    const Json items = ws.lastEnvelope()["data"]["home"][1]["items"];
    ASSERT_EQ(1u, items.size());
    EXPECT_EQ("\xc3\x89" "clairage caf\xc3\xa9", items[0].value("name", std::string()));
}

