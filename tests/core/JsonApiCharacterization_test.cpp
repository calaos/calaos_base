TEST_F(JsonApiCharacterizationTestSuite, HttpWrongCredentialsGetA400AndACloseRequest)
{
    //sendLoginFailed() dereferences httpClient without a guard: this case is
    //the proof that a real HttpClient on an unconnected socket is enough to
    //characterize the HTTP side, error paths included.
    loadReferenceHouse();

    HttpTestRequest req;
    req.send(Json{{ "action", "get_home" },
                  { "cn_user", "wrong" },
                  { "cn_pass", "wrong" }});

    ASSERT_EQ(1u, req.count());
    EXPECT_EQ("HTTP/1.0 400 Bad Request", req.statusLine());
    EXPECT_EQ("text/html", req.header("Content-Type"));
    ASSERT_EQ(1u, req.closes().size());
    EXPECT_EQ(0, req.closes().front().first);
}

