/*******************************************************************************
 * E4.0a - the foundation of the JSON API characterization net, proven end to
 * end.
 *
 * This file is NOT the characterization campaign. E4.0b..E4.0f are. What it
 * has to demonstrate is that every mechanism of the harness works against the
 * real production code, so the five sub-tickets can start on it without
 * re-litigating anything:
 *
 *   - the semantic oracle behaves as specified (key order blind, array order
 *     significant, strict on types),
 *   - a golden file round trips: generated by the code, compared semantically,
 *   - a plain WS command answers a full payload (get_home),
 *   - a WS command with a second level of dispatch reaches its sub-handler
 *     (audio / audio_action),
 *   - the error and silence paths are observable (unknown action, unknown
 *     autoscenario type, command before login),
 *   - the HTTP transport is drivable with a real HttpClient built on an
 *     unconnected socket, headers included,
 *   - events are delivered once, and only once, the uvw loop is pumped.
 *
 * Everything here records the behaviour that exists today. Two cases pin what
 * are, unambiguously, production bugs (the autoscenario silence, the "unkown
 * audio_action" typo). They are frozen on purpose: fixing a behaviour while
 * characterizing it destroys the reference.
 ******************************************************************************/

