/******************************************************************************
 * Constant time comparison (F2)
 ******************************************************************************/

TEST(JsonApiSecureCompare, AcceptsIdenticalSecrets)
{
    EXPECT_TRUE(JsonApi::secureCompare("s3cr3t", "s3cr3t"));
    EXPECT_TRUE(JsonApi::secureCompare("", ""));

    //A real token: 64 hex chars, as generated by RAND_bytes
    const std::string token(64, 'a');
    EXPECT_TRUE(JsonApi::secureCompare(token, token));
}

TEST(JsonApiSecureCompare, RejectsDifferentSecrets)
{
    EXPECT_FALSE(JsonApi::secureCompare("s3cr3t", "S3cr3t"));
    EXPECT_FALSE(JsonApi::secureCompare("s3cr3t", "s3cr3T"));
    EXPECT_FALSE(JsonApi::secureCompare("s3cr3t", ""));
    EXPECT_FALSE(JsonApi::secureCompare("", "s3cr3t"));
}

TEST(JsonApiSecureCompare, RejectsPrefixOfTheSecret)
{
    //The old std::equal based check returned on the first differing byte and
    //compared sizes first, both leaking information through timing
    EXPECT_FALSE(JsonApi::secureCompare("s3cr3t", "s3cr"));
    EXPECT_FALSE(JsonApi::secureCompare("s3cr", "s3cr3t"));
}

TEST(JsonApiSecureCompare, HandlesEmbeddedNulBytes)
{
    std::string a("ab\0cd", 5);
    std::string b("ab\0ce", 5);

    EXPECT_TRUE(JsonApi::secureCompare(a, a));
    EXPECT_FALSE(JsonApi::secureCompare(a, b));
}

